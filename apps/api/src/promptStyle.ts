/**
 * 共享表达风格段：5 个候选 Agent prompt 与对话运行时统一拼接，不再各自复制。
 * 面向 CEO 的业务文本（summary、回复正文、entries、consequences 等）都按这组约束写。
 * 参考 ~/.agents/skills/human-writing/SKILL.md「成稿绝对不能出现」，按业务文档语境收敛。
 */

/** 翻案句核心变体：label 进风格段，pattern 留给服务端校验，两处同源。 */
export const TURN_PHRASE_PATTERNS: { label: string; pattern: RegExp }[] = [
  { label: "不是……而是……", pattern: /不是[^。！？\n]{0,40}?而是/ },
  { label: "并非……而是……", pattern: /并非[^。！？\n]{0,40}?而是/ },
  { label: "不在于……而在于……", pattern: /不在于[^。！？\n]{0,40}?而在于/ },
  { label: "与其说……不如说……", pattern: /与其说[^。！？\n]{0,40}?不如说/ },
];

/** 同一动作的其他字面变体：只写进风格段提示，不做服务端拒绝。 */
const TURN_PHRASE_EXTRA_LABELS = [
  "表面……实际……",
  "看似……实则……",
  "你以为……其实……",
  "回头看才发现",
  "说到底",
  "答案恰恰相反",
  "A 不重要，重要的是 B",
];

const TURN_PHRASE_LABELS = [...TURN_PHRASE_PATTERNS.map(({ label }) => label), ...TURN_PHRASE_EXTRA_LABELS]
  .map((label) => `“${label}”`)
  .join("");

export const HUMAN_WRITING_STYLE = `# 表达要求（自然中文）

面向 CEO 的文字用自然中文写，判断从正面直接下：先给判断，再给依据。以下写法一律不用，禁的是修辞动作，换一套字做同一个动作仍然算命中。

1. 翻案句：先立一个对方并没有的误解，再推翻它给下文抬价。禁止${TURN_PHRASE_LABELS}，以及同一动作的任何字面变体。
2. 洞察路标：“值得注意的是”“需要指出的是”“更微妙的是”“还有一层”“只说对了一半”“从某种意义上说”“说白了”“说穿了”“先说结论”。
3. 动词名词化。“完成了对流程的优化”写成“把流程改顺了”，“实现了效率的提升”写成“快了多少、省了几个人”。
4. 三项以上同构排比。两项为限，第三项换一种说法或者删掉。
5. 散文文本不用破折号 —、——、–；提示性冒号（“核心是：”）不用，冒号只留引出直接原话。字段名、URL、列表结构不受限。
6. 商业黑话与模型腔（赋能、抱团、闭环、拉齐、彻底重塑、重新定义等）不用来给普通事情抬价。
7. 给抽象名词配具体动词写抒情（“时间不会保管细节”“焦虑会显出形状”）。真在写具体事物时不受影响。
8. 非虚构文本不用借喻包装抽象概念（仓库、抽屉、温度、死亡、坍塌、浪潮、钥匙、底座等）。真在写这些东西时不受影响。
9. 原话命中以上任何一条时改成转述或省略，不能靠引号保留。`;
