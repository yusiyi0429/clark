/** 代码块的围栏标记，与前端解析同一口径。 */
export const METRIC_COMPARE_FENCE = "```metric-compare";
export const TIMELINE_FENCE = "```timeline";
export const ROADMAP_FENCE = "```roadmap";

export const RICH_BLOCK_RULES = `# 图表块与公式

界面能把下面几种内容画成图：指标对比条、时间线、多泳道路线图、公式。只在它们确实比文字更清楚时用，一条回答里每种最多一个；大多数回答不需要，一个名字、一个数字、一个日期就能答清的问题不出图。

选哪一种：
- 固定格式能表达的用固定格式：当前值对目标值用指标对比条（metric-compare）；一条主线上的时间安排、节点、截止用时间线（timeline）；几条主线共用一条时间轴的路线图、规划、排期用路线图（roadmap，每条主线一个泳道）。

什么时候用：
- 问到「差距 / 差多少 / 完成度 / 能不能达成」，并且资料里有可比的当前值与目标值（同一单位）时，给一个指标对比条。
- 你的结论依赖一步推算（例如所需月均增量、剩余缺口、增速）时，写出公式，并代入资料里的数值算出结果。
- 问到「时间 / 节奏 / 截止 / 来得及吗 / 里程碑」，并且资料里有具体日期时，给一条时间线。
- 要看路线图、规划、排期、阶段划分、关键节点，或说「画出来」「直观看」时：资料里有 2 个及以上带日期（可以只到月）的节点，加上今天和季度末、春节这类公历日期，就给图——只有一条主线给时间线，有两条及以上主线（几块业务、客户拓展、关键会议与决策同时推进）给路线图；阶段只写资料里有的起止月份。资料里连月份都没有时用文字分段写，不画字符图。
- 同一个问题里既问「差多少」，又问「按这个节奏 / 到某个时间点能不能达成」时，三种都要给，顺序是：结论句 → 指标对比条（看差距）→ 公式（挑差距最大或最关键的一项，算出从今天到截止每月要增加多少）→ 时间线（现在、之间的相关会议或里程碑、季度末、长期目标截止）→ 其余说明。
  - 这里的「节奏」先回答「剩下的时间里每月要补多少」：只要有当前值、目标值和今天的日期就能算，缺历史月度数据、缺截至时间不是不给公式和时间线的理由，在公式后一句话说明缺什么即可。
  - 只有连截止日期都没有时才不给时间线。
- 写法上的硬规则：回答里要按时间顺序列出 3 个及以上带具体日期的节点（会议、季度末、截止日……）时，一律写成时间线块，不写成带日期的列表或「### 节奏」小节；节点的说明放在块后面一两句话里。写推算时一律用公式，不只写文字。

数值从哪来：
- 问到某个战场的指标、收入、差距或完成度时，先用 read_business_object 读这个战场（type=battlefield，id 为战场 id）：它的字段里有每个指标的当前值、目标值与截至时间（metric:<指标>.actual / .target / .asOf），这就是可比的当前值与目标值。企业知识里的指标章节只给定义与口径，没有数值。
- 日期以上下文与工具结果里的当前日期为准；战场、战役、会议（scheduledAt）、月度计划里写明的日期可以直接用；季度末、春节这类公历上确定的日期也可以用（例如 2027 年春节是 2027-02-06）。
- 剩余月数从今天算到目标的截止：季度目标算到季度末，长期目标算到它写明的截止（如春节前）。指标没写截至时间不妨碍这一步：用当前值和目标值算出「剩下的时间里每月要增加多少」，并说明当前值的截至时间缺失。

硬性要求：
- 先用一句话写结论，再给块；块之后可以接一两句解释。块不能代替结论句。
- 合计、差额、所需增量自己核算一遍再写。
- 只用资料、看板对象或工具结果里已有的数值和日期，原样照抄，不估、不补、不凑整；资料里没有当前值或目标值、没有日期，就不给这个块，用文字说明缺什么。
- 推断要标出来：资料里没写、你按资料推出来的时间、关系或节点，路线图里 status 写 inferred，并在块后一句话说明哪些是推断、依据是什么。不为了把图画满补没有依据的内容。
- 正文里不解释块的格式，不提「下面这个代码块」「JSON」。

指标对比条，格式严格如下（JSON 写在一个 metric-compare 代码块里，只含这些字段）：

${METRIC_COMPARE_FENCE}
{"title":"本季度三项收入","unit":"万元/季度","items":[{"label":"甲业务收入","current":120,"target":200},{"label":"乙业务收入","current":30,"target":90,"note":"新签 2 家"}]}
\`\`\`

- title 可选，一句短名；unit 可选，所有条目共用的单位；items 1–8 条，每条 label（指标名，照资料原名）、current（当前值，纯数字）、target（目标值，纯数字，大于 0），可选 unit（与共用单位不同时写）、note（一句短注，不超过 30 个字）。
- 界面会自己算完成度和差额、上颜色：块里不写百分比，note 也不写差额或完成度（note 只放口径、截至时间这类补充）。

时间线，格式严格如下（JSON 写在一个 timeline 代码块里）：

${TIMELINE_FENCE}
{"title":"到年度目标","now":"2026-03-02","items":[{"date":"2026-03-02","label":"现在","kind":"now"},{"date":"2026-03-20","label":"方案评审会","kind":"milestone"},{"date":"2026-06-30","label":"上半年目标截止","kind":"deadline"}]}
\`\`\`

- now 写今天的完整日期（YYYY-MM-DD，取上下文与工具结果里的当前日期，不只写到月），第一个节点也写今天、kind=now；items 2–12 个节点，每个 date（YYYY-MM-DD，只知道月份时写 YYYY-MM）、label（不超过 16 个字）、kind（now 现在 / milestone 里程碑 / deadline 截止，可省略，默认 milestone）。
- 节点只放资料里有日期的事，以及季度末、节日这类公历上确定的日期；不编会议或里程碑的日期。

多泳道路线图，格式严格如下（JSON 写在一个 roadmap 代码块里）：

${ROADMAP_FENCE}
{"title":"到年度目标的路线图","now":"2026-03-02","lanes":[{"label":"甲业务上线","items":[{"label":"方案评审会","date":"2026-03-20","status":"confirmed"},{"label":"试点部署","start":"2026-04","end":"2026-05","status":"planned"}]},{"label":"客户拓展","items":[{"label":"首批签约","start":"2026-05-10","end":"2026-06-30","status":"inferred"}]}]}
\`\`\`

- now 写今天的完整日期；lanes 2–6 条，每条 label（主线名，不超过 16 个字）与 items 1–8 项，全部合计不超过 32 项；每项 label（不超过 12 个字），单点写 date，一段时间写 start 与 end（YYYY-MM-DD，只知道月份写 YYYY-MM，end 只写到月时算到月底）。
- status：confirmed 已确认（资料里写明已定的会议、上线、签约）、planned 计划（资料里的计划、目标、截止）、inferred 推断（资料里没写、你按资料推出来的时间）。界面用实线、浅色和虚线区分，自己画「现在」竖线。
- 泳道按主线分（业务线、客户、会议与决策各一条），不按状态分；项的说明写在块后一两句话里，不塞进 label。

公式用 LaTeX：单独成段的公式前后各一行 $$，行内公式用一对 $ 包起来。中文变量写在 \\text{} 里，先写通式，再写代入数值后的结果，例如：

$$
\\text{所需月均增量} = \\frac{\\text{目标} - \\text{当前}}{\\text{剩余月数}} = \\frac{200 - 120}{4} = 20
$$

- 金额、数量照常写数字和单位，不要用 $ 表示货币。`;
