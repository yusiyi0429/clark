module.exports = async function ({ ceoContext, memberContext, ceo, member, targets, root, card, action, responseJson, capture, sizes, save, log, control, assert }) {
  const noteLabel = '跨人员依赖、冲突与协作的核对结论';
  const region = page => page.getByRole('region', { name: '本轮', exact: true });
  const note = (page, id) => page.locator(`[data-feedback="${id}"]`);
  const current = () => card(ceoContext, targets.cardId);
  const targetUrl = root + '/mission-cards/' + targets.cardId;
  const settle = () => ceo.waitForTimeout(700);
  ceo.on('pageerror', error => log('page-error', { role: 'ceo', message: error.message }));
  member.on('pageerror', error => log('page-error', { role: 'member', message: error.message }));
  await ceo.goto(targetUrl); await member.reload();
  let view = await current();
  const first = view.payload.feedback.find(f => f.field === 'outcome' && f.id !== targets.secondFeedbackId);
  const milestone = view.payload.feedback.find(f => f.field === 'milestones'); assert(first && milestone);
  if (view.payload.round.counts.pending > 0) {
  await ceo.getByRole('button', { name: '从第一条开始', exact: true }).waitFor();
  await sizes(ceo, 'review-initial', region(ceo));
  // First pending belongs to another card; the entry must move and focus the actual opinion.
  await ceo.getByRole('button', { name: '从第一条开始', exact: true }).click();
  await ceo.waitForURL('**/' + targets.otherCardId + '?feedback=*'); await settle();
  const destination = await ceo.evaluate(() => ({ path: location.pathname, active: document.activeElement?.id, query: location.search }));
  assert(destination.active?.startsWith('feedback-')); log('cross-card-first-pending', destination);
  await ceo.getByRole('button', { name: '已纳入核对', exact: true }).click(); await settle();
  await ceo.getByRole('button', { name: '从第一条开始', exact: true }).click();
  await ceo.waitForURL('**/' + targets.cardId + '?feedback=*'); await settle();
  view = await current();
  const beforeToken = first.actions[0].actionId;
  await note(ceo, first.id).getByRole('button', { name: '采纳修改', exact: true }).click();
  await note(ceo, first.id).getByText('已采纳 · 拍板前可能变化', { exact: true }).waitFor();
  assert(await note(ceo, targets.secondFeedbackId).getByRole('button', { name: '采纳修改', exact: true }).isDisabled());
  await sizes(ceo, 'field-conflict', note(ceo, targets.secondFeedbackId));
  view = await current();
  const conflict = await action(ceoContext, view.payload.feedback.find(f => f.id === targets.secondFeedbackId).actions[0].actionId, targets.cardId, { decision: 'accept' });
  assert.equal(conflict.status(), 409); assert.equal((await conflict.json()).code, 'CONFLICTING_SUGGESTION');
  const stale = await action(ceoContext, beforeToken, targets.cardId, { decision: 'decline' }); assert.equal(stale.status(), 409);
  const replay = await responseJson(await action(ceoContext, beforeToken, targets.cardId, { decision: 'accept' })); assert.equal(replay.cards[0].version, view.version);
  await note(member, first.id).getByText('已采纳 · 拍板前可能变化', { exact: true }).waitFor({ timeout: 15000 });
  assert.equal(await member.getByRole('button', { name: '采纳修改', exact: true }).count(), 0);
  await member.getByRole('log', { name: '事项群组公开讨论' }).getByText('已采纳 · 拍板前可能变化', { exact: true }).waitFor({ timeout: 15000 });
  log('conflict-stale-replay-and-live-member', { conflictStatus: 409, staleStatus: 409, replayVersion: view.version, memberSynchronizedWithoutReload: true });
  await sizes(member, 'member-candidate', note(member, first.id));
  await note(ceo, targets.secondFeedbackId).getByRole('button', { name: '不采纳', exact: true }).click(); await settle();
  await note(ceo, milestone.id).getByRole('button', { name: '采纳修改', exact: true }).click(); await settle();
  }
  await ceo.getByRole('button', { name: '确认前核对', exact: true }).click();
  await ceo.getByLabel(noteLabel, { exact: true }).waitFor();
  assert(await ceo.getByRole('button', { name: '确认本月 Mission Card', exact: true }).isDisabled());
  await sizes(ceo, 'confirm-empty', ceo.getByLabel(noteLabel, { exact: true }));
  await ceo.getByLabel(noteLabel, { exact: true }).fill('此结论必须在重开后作废，不能跨轮沿用。');
  await ceo.getByRole('button', { name: /打开白田田的 Mission Card/ }).click();
  await ceo.waitForURL('**/' + targets.otherCardId); await settle();
  const expandOther = ceo.getByRole('button', { name: '展开本轮详情', exact: true }); if (await expandOther.count()) await expandOther.click();
  await ceo.getByRole('button', { name: /打开孙铭泽的 Mission Card/ }).click();
  await ceo.waitForURL('**/' + targets.cardId); await settle();
  await ceo.getByRole('button', { name: '确认前核对', exact: true }).click();
  assert.equal(await ceo.getByLabel(noteLabel, { exact: true }).inputValue(), '此结论必须在重开后作废，不能跨轮沿用。');
  log('collaboration-note-survives-card-navigation');
  await ceo.setViewportSize({ width:390, height:844 });
  await ceo.getByRole('button', { name: '确认前核对', exact: true }).click(); await settle();
  const inputBox = await ceo.getByLabel(noteLabel, { exact:true }).boundingBox();
  const dockBox = await ceo.getByRole('textbox', { name:'事项群组输入' }).boundingBox();
  assert(inputBox.y + inputBox.height < dockBox.y, 'Real phone focus must keep the entire note above the dock');
  await ceo.getByLabel(noteLabel, { exact:true }).fill('手机长文核对。'.repeat(100));
  await capture(ceo, 'phone-note-focused');
  log('phone-note-visible-after-real-focus', { inputBottom: inputBox.y+inputBox.height, dockTop:dockBox.y, longInput:700 });
  await ceo.getByLabel(noteLabel, { exact:true }).fill('此结论必须在重开后作废，不能跨轮沿用。');
  await ceo.route('**/api/mission-rounds/actions/execute', route => route.abort('failed'));
  await ceo.getByRole('button', { name: '确认本月 Mission Card', exact: true }).click();
  await ceo.getByRole('alert').filter({ hasText: '本轮输入已保留' }).first().waitFor();
  assert.equal(await ceo.getByLabel(noteLabel, { exact: true }).inputValue(), '此结论必须在重开后作废，不能跨轮沿用。');
  await sizes(ceo, 'confirm-network-retry', ceo.getByRole('button', { name: '确认本月 Mission Card', exact: true }));
  await ceo.unroute('**/api/mission-rounds/actions/execute');
  log('network-failure-preserves-note-and-keeps-reviewing', { phase: (await current()).payload.round.phase });
  const late = await responseJson(await memberContext.request.post(root + `/api/mission-cards/${targets.cardId}/feedback`, { headers: { origin: root }, data: { clientId: crypto.randomUUID(), kind: 'comment', round: 1, body: '截止后补充：第二轮请核对共同验收日程。' } }));
  save('browser-before-reopen.json', control('inspect'));
  await ceo.getByRole('button', { name: '重新开启 48 小时', exact: true }).click();
  const dialog = ceo.getByRole('alertdialog', { name: '请确认' }); await dialog.waitFor();
  await sizes(ceo, 'reopen-dialog', dialog);
  await dialog.getByRole('button', { name: '重新开启 48 小时', exact: true }).click(); await settle();
  await note(ceo, first.id).getByText('上一轮已采纳 · 下次截止沿用', { exact: true }).waitFor();
  assert.equal(await ceo.getByLabel(noteLabel, { exact: true }).count(), 0);
  await sizes(ceo, 'reopened', region(ceo));
  save('browser-cutoff-2.json', control('advance'));
  await ceo.reload(); await settle();
  view = await current(); assert.equal(view.payload.round.round, 2); assert.equal(view.payload.round.counts.pending, 1);
  assert.equal(view.payload.card.missions.find(m => m.missionId === targets.missionId).outcome, first.proposed);
  await note(ceo, late.feedback.id).getByRole('button', { name: '已纳入核对', exact: true }).click(); await settle();
  await ceo.getByRole('button', { name: '确认前核对', exact: true }).click();
  assert.equal(await ceo.getByLabel(noteLabel, { exact: true }).inputValue(), '');
  const latest = await current(); const confirm = latest.actions.find(a => a.actionType === 'mission-round.confirm'); assert(confirm);
  const empty = await action(ceoContext, confirm.actionId, targets.cardId, { note: '   ' }); assert.equal(empty.status(), 400);
  // New late feedback after the second cutoff must not block the current confirmation.
  await responseJson(await memberContext.request.post(root + `/api/mission-cards/${targets.cardId}/feedback`, { headers: { origin: root }, data: { clientId: crypto.randomUUID(), kind: 'comment', round: 2, body: '本轮截止后留档：验收材料路径已经补充。' } }));
  const conclusion = '已逐人核对 10 月 15 日接口交接与 10 月 25 日联合验收；冲突建议保留第一版结果，资源与验收责任无重叠。';
  await ceo.getByLabel(noteLabel, { exact: true }).fill(conclusion);
  await sizes(ceo, 'confirm-ready', ceo.getByLabel(noteLabel, { exact: true }));
  await sizes(ceo, 'confirm-action', ceo.getByRole('button', { name: '确认本月 Mission Card', exact: true }));
  await ceo.getByRole('button', { name: '确认本月 Mission Card', exact: true }).click();
  await ceo.getByRole('region', { name: '确认记录', exact: true }).waitFor();
  let final = await current(); assert.equal(final.payload.round.phase, 'confirmed');
  assert.equal(final.payload.confirmation.note, conclusion);
  const confirmedReplay = await responseJson(await action(ceoContext, confirm.actionId, targets.cardId, { note: conclusion }));
  assert.equal(confirmedReplay.cards[0].version, final.version);
  const denied = await memberContext.request.post(root + `/api/mission-cards/${targets.cardId}/feedback`, { headers: { origin: root }, data: { clientId: crypto.randomUUID(), kind: 'comment', round: 2, body: '确认后必须拒绝' } }); assert.equal(denied.status(), 409);
  const reopen = latest.actions.find(a => a.actionType === 'mission-round.reopen'); assert(reopen);
  assert.equal((await action(ceoContext, reopen.actionId, targets.cardId)).status(), 409);
  await member.getByText('已确定', { exact: true }).first().waitFor({ timeout: 15000 });
  for (const page of [ceo, member]) {
    for (const name of ['采纳修改', '不采纳', '引用到群组', '建议修改', '重新开启 48 小时', '确认本月 Mission Card']) assert.equal(await page.getByRole('button', { name, exact: true }).count(), 0);
    await sizes(page, page === ceo ? 'ceo-confirmed' : 'member-confirmed', page.getByRole('region', { name: '确认记录', exact: true }));
  }
  const before = JSON.parse(require('node:fs').readFileSync(require('node:path').join(__dirname, 'browser-before.json'), 'utf8')).result;
  const finalState = control('inspect'); save('browser-final.json', finalState);
  const after = finalState.result;
  for (const oldMission of before.missions) {
    const newMission = after.missions.find(m => m.id === oldMission.id); assert(newMission);
    if (newMission.id === targets.missionId) {
      assert.equal(newMission.version, oldMission.version + 1);
      assert.equal(newMission.outcome, first.proposed);
      assert.deepEqual(newMission.milestones, ['10 月 15 日 · 完成接口核对', '10 月 25 日 · 联合验收']);
      for (const key of Object.keys(oldMission).filter(k => !['version', 'outcome', 'milestones'].includes(k))) assert.deepEqual(newMission[key], oldMission[key]);
    } else assert.deepEqual(newMission, oldMission);
  }
  assert.equal(after.reviews.length, 2); assert.equal(after.reviews[0].note, null);
  assert.equal(after.reviews[1].applied_versions[targets.missionId], 2);
  log('confirmed-end-to-end', { changedMissions: 1, updatedFields: ['outcome', 'milestones'], missionVersion: 2, reviews: 2, feedback: after.feedback.length, replayVersion: final.version, unchangedMissions: 11 });
  await ceo.goto(root + '/missions/' + targets.missionId);
  await ceo.getByRole('link', { name: /个人卡/ }).first().waitFor();
  await sizes(ceo, 'mission-confirmed');
};
