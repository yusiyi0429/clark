/** 探查：打开、Esc 关掉、再打开提问弹窗时控制台的警告；关掉后已选的是否保留。node .scratch/ask-panel/probe.mjs <reviewId> */
const { chromium } = await import("file:///C:/Users/10021/Desktop/clark/ts-design/node_modules/playwright-core/index.mjs");
const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "zh-CN" })).newPage();
const log = (...args) => console.log(...args);
page.on("console", (message) => { if (["warning", "error"].includes(message.type())) log("console", message.type(), message.text().slice(0, 160)); });
await page.goto("http://localhost:3600/access");
await page.getByLabel("你的 ID").fill("ceshiy");
await page.getByLabel("口令第 1 位").click();
for (const digit of "1357") await page.keyboard.press(digit);
await page.waitForURL((url) => !url.pathname.startsWith("/access"));
await page.goto(`http://localhost:3600/me/reviews/personal/${process.argv[2]}`);
const start = page.getByTestId("ask-start").last();
await start.waitFor({ timeout: 60_000 });
log("step: open");
await start.click();
await page.getByTestId("ask-dialog").waitFor();
await page.waitForTimeout(500);
log("focused", await page.evaluate(() => document.activeElement?.textContent));
log("step: pick 2");
await page.keyboard.press("2");
await page.waitForTimeout(400);
log("step: escape");
await page.keyboard.press("Escape");
await page.getByTestId("ask-dialog").waitFor({ state: "detached" });
log("step: reopen");
await start.click();
await page.getByTestId("ask-dialog").waitFor();
await page.waitForTimeout(400);
log("checked", await page.locator("[role=radio][aria-checked=true]").allInnerTexts());
await page.getByRole("button", { name: "关闭" }).click();
await page.waitForTimeout(400);
log("done");
await browser.close();
