export type A4Input = {
  issueId: string;
  title: string;
  scope: string | null;
  /** 预研的结论，深研要接着它往下走，不能从头再来一遍。 */
  preTake: string | null;
  preOpenQuestions: string[];
  /**
   * 一号位在提问里**明确给定**的研究前提（预研那一轮记下来的 `PreResearchDoc.premises`）。
   *
   * 它在 N1 就要出现（2026-09-07，ISS-239）：草稿是命题的来源，而「我方已经实现了什么」这类
   * 前提如果要到 N5 才第一次露面，这一轮去查什么就完全不受它影响 —— 239 那一轮推荐了一条
   * 产线验收的入口，全程没有一步核过 TKOS 现在做不做得了工艺侧的事。
   *
   * **身份要留住**：它是研究前提，不是已核过的外部事实，也不写进本体。
   */
  userPremises?: readonly { text: string; quote?: string }[];
  /**
   * 预研那一轮**已经核过**的证据。同一个议题、同一套记账规则。
   *
   * ## 今天生产上恒为 undefined —— 这一栏只有接收侧
   *
   * 传它的那一句还不存在：`store.ts` 构造深研入参时没有这一栏，而更根本的是
   * **`PreResearchDoc` 上没有地方存证据**（那是预研层 v2 计划里 `stages` 那个字段的事，
   * 而 v2 一行未动）。所以下面 `pipeline.ts` 垫台账那两条路、以及报告文首那句「正文里的
   * 证据全部来自预研那一轮」，今天在真机上都走不到，只有测试跑得到。
   *
   * **先建接收侧是有意的**：等 v2 的 `stages` 落地时，要改的只有 `store.ts` 那一句。
   * 但这件事必须写在这里 —— 一栏「看着已经接上、实际没有生产者」的入参，是这个仓库
   * 反复在防的那种陷阱，而防它的办法就是把话说在类型上。
   *
   * 它和 `preTake` 是两件事：`preTake` 是那一轮的**结论**（一段话，深研接着它往下走），
   * 这一栏是那一轮**查到的东西**（带引句、跨度、档次的条目）。原来只传结论不传证据，
   * 于是 A4 起跑时又从零搜一遍 —— 同一个议题、同一套检索源、隔了不久，搜回来的东西
   * 大面积重叠。
   *
   * **可选，而且常常是空的**：预研可能没联网，也可能那一轮取证一条都没入账。
   * 下游一律按空的写 —— 非空是意外之喜，不是可以依赖的前提。
   */
  preEvidence?: readonly Evidence[];
  /*
   * **这里没有「内部文档」那一栏，是有意的。**
   *
   * 本地那个文档库（`store.docs`）曾经整批进 prompt，挑法是 `pickDocs`：按「有没有正文」
   * 排序取前十份，跟这条议题相不相干一概不问。而库里有正文的只有四份 —— 于是**每一件议题、
   * 每一轮深研读到的都是同一批文档**。ISS-120 那份维信诺首访的报告里，Oasis 那份研究稿被
   * 引了 34 次，判断板上跟着写出「内部研究已将受控地把工作交给 AI 定为 TKOS 的长期产品原则
   * （DOC-D4）」—— 手上只有这个所以引这个，而它在报告里和真正相关的出处长得一模一样。
   *
   * 所以公司内部材料现在只有一个来源：本体（`companyContext`）。要接真的内部文档，从本体
   * 接；在这里加一栏「顺手也把库里的带上」，等于把上面那件事原样再做一遍。
   */
  judgments: Pick<Judgment, "id" | "statement" | "standing">[];
};

