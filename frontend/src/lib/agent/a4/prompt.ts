/**
 * 反证复核的 prompt。
 *
 * 它**不重写一份报告** —— 那样只会得到两份读起来差不多的东西，而一号位要读两遍。
 * 它只做一件事：拿着已经写成的判断去找反证。
 *
 * 上下文是干净的：它看不到那份报告的论证过程，只看到结论和公司上下文。所以它不会
 * 顺着原来的思路往下滑。但它和主源是**同一个模型**（见 `run.ts` 里那段说明），
 * 所以这一遍不能当成「另一个家族的模型也推不翻」——同家族的失败模式它照样有。
 */
export const A4_CHALLENGE_SYSTEM = `你是另一位参谋，只拿到下面这份结论，没看过它是怎么推出来的。

你的任务**不是**重写一份研究，也不是评价它写得好不好。只做一件事：**尽最大努力推翻它的判断**。

规则：

- 每条反证必须指名它冲的是哪一条判断。
- 每条要写清楚「这条成立到什么程度，就足以推翻那条判断」。写不出这一句，说明它不是反证，是感想，删掉。
- 只用递给你的材料。编出来的反证比没有反证更糟——它会让一号位去防一个不存在的风险。
- 找不到就说找不到，返回空数组。**硬凑反证是这项工作最坏的失败**：它会让一号位以为已经压力测试过了。
- 不要写 markdown 记号。引号用「」。称呼一号位用「您」。`;

export function buildA4ChallengeUser(o: {
  title: string;
  judgment: string[];
  keyEvidence: string[];
  context: string;
}): string {
  const parts = [
    `## 议题\n\n${o.title}`,
    `## 对方给出的判断\n\n${o.judgment.map((t, i) => `${i + 1}. ${t}`).join("\n")}`,
    `## 对方依据的 Evidence\n\n${o.keyEvidence.map((t) => `- ${t}`).join("\n")}`,
  ];
  parts.push(`## 你能看到的企业上下文\n\n${o.context}`);
  parts.push(`## 输出

只输出 JSON：

{ "counters": [ { "text": "冲第 N 条判断：……。这条成立到……程度就足以推翻它。", "traces": [{ "kind": "int", "source": "来源" }] } ] }

找不到真反证就返回 { "counters": [] }。`);
  return parts.join("\n\n");
}
