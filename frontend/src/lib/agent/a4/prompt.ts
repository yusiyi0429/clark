/**
 * A4 Deep Research 的 prompt。**取证在前，写作在后，两层交付。**
 *
 * ## 链路
 *
 *  1. `a4.props`：把议题编译成几条**可证伪的命题**，各带检索式和一条反向检索式。
 *     在任何检索之前跑 —— 先搜再定题，问题框架会被第一页搜索结果锚住。
 *  2. `a4.extract`：一页一次，从抓回来的正文里抽原子证据。抽取器不下判断，只回答
 *     「这页里有没有能回答这几条命题的原句」。
 *  3. `a4.report`：按 S03 §6 写那份正式报告。**只看证据包，看不到原始网页** ——
 *     正文事实一律绑 `[E编号]`，地址由代码绑（见 `gate.ts`）。
 *  4. `a4.digest`：把**已经写成的那份报告**压成四节 JSON。
 *  5. `a4.challenge`：拿着结论去找反证。
 *
 * 前三步**每条链路各跑一遍**：一轮深研有四条独立链路（DeepSeek / Claude / ChatGPT /
 * 豆包），各自编命题、各自取证、各自写报告，所以这一份 prompt 一轮里被装配
 * 几次，只换模型。**条数以 `run.ts` 的 `LANES` 为准** —— 这里写的数只是为了让人读得出
 * 「不止一条」，别把它当契约。
 * 后两步只跑在主源那条链路的报告上（见 `run.ts` 的链路表）。
 *
 * ## 为什么报告和四节是两次调用
 *
 * 交付是两层：`sourceText` 是那份可署名分发的正式报告（S03 §6），四节是屏幕上按条读的
 * 压缩面。四节也不能删 —— 判断板（A5）、划词溯源、探讨链路的双向锚全都按字段取值。
 *
 * 顺序是**先报告、后压缩**。倒过来的话报告就是四节的注水版，§6 那条「章节标题本身就是
 * 判断」永远长不出来。压缩面不许出现报告里没有的判断：两层说的不是一件事，一号位在同一个
 * 页签下切两下就会看到两份结论，而他没法知道该信哪一份。
 *
 * ## 没配检索的机器上还是能跑
 *
 * 一台没配检索 key 的机器不该让深研整条失败（HP-5）。那种情况下走 `a4ReportSystem(false)`
 * 这一支：外部事实只能来自模型既有知识，报告里照实写明本轮未联网核验。这一支的风险是
 * 「结论只有模型记忆撑着」，所以那一句不许省 —— 它不是免责，是让人知道哪几条在落地引用
 * 之前要先核一遍。
 */
