/** 议题、预研结论、在版判断、公司上下文。两层里只有报告那一层要全套。 */
export function buildA4Material(input: A4Input & { companyContext: string }): string {
  const parts: string[] = [];
  parts.push(`## 议题\n\n${input.title}（编号 ${input.issueId}）`);
  if (input.scope) parts.push(`范围与背景：${input.scope}`);

  if (input.preTake) {
    parts.push(
      `## 这个议题的预研结论\n\n${input.preTake}\n\n` +
        `深研要**接着它往下走**，不是从头再来一遍。预研已经说过的话不要重复说；` +
        `如果深研的材料推翻了预研的判断，明说推翻了哪一句。`
    );
  }
  if (input.preOpenQuestions.length) {
    parts.push(
      `## 预研当时答不上来的（升级深研正是为了查这些）\n\n` +
        input.preOpenQuestions.map((q) => `- ${q}`).join("\n") +
        `\n\n这几条现在答上了几条，要在报告里看得出来。答不上的照实写明还差什么。`
    );
  }

  if (input.judgments.length) {
    parts.push(
      `## 这个议题正在动摇的在版判断\n\n` +
        input.judgments.map((j) => `- ${j.id}（${j.standing}）：${j.statement}`).join("\n") +
        `\n\n如果结论要改其中某一条，在报告里点名是哪一条、改成什么。`
    );
  }
  // 见 a3/prompt.ts 上同一处的注释：这一段永远存在，纯外部时是那两档兜底文本之一。
  parts.push(`## 公司决策上下文（GraphKnowledge S03）\n\n${input.companyContext}`);
  return parts.join("\n\n");
}

