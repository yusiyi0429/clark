/** 出口校验器拒掉的一个块。`at` 是它在这一份里排第几（从 1 数），和违规原话里那个号一致。 */
export type RejectedBlock = {
  at: number;
  /** 这个块原样交上来的那一行 JSON。 */
  line: string;
  /** 为什么被拒。一条块上可能有几条，合成一段。 */
  why: string;
};

/**
 * 只重发被拒的那几块。
 *
 * 让模型重写整篇的代价不只是 token：**它会顺手改掉没被拒的那几块**，而那几块已经过闸了。
 * 于是第二稿里冒出来的新问题没人能解释是哪来的 —— 一号位读到的是两份不同的报告，而台账
 * 上只记着「重写了一轮」。
 *
 * 所以这一轮的回复只有那几行：顺序和下面列出的顺序一致，一行一个块，别的什么都不要写。
 * 顺序是唯一的对齐方式，所以这句话要说两遍（列表前一遍，输出要求里一遍）。
 *
 * `needsMeta` 是唯一的例外：`report_meta` 那一行缺了或者写坏了的时候，它不属于任何一个块，
 * 拿不到「第几个块」这个号，也没法在别的块里就近改。那一种只能让它把那一行重交一遍 ——
 * 于是这一轮的行数是「块数 + 1」，而 report_meta 从「不要写」变成「第一行必须是它」。
 */
export function buildA4BlockRepair(rejected: RejectedBlock[], general?: string, needsMeta?: boolean): string {
  const list = rejected
    .map(
      (r, i) =>
        `### 第 ${i + 1} 块（这一份里的第 ${r.at} 个块）\n\n没过的原因：${r.why}\n\n原样交上来的是：\n\n${r.line}`
    )
    .join("\n\n");
  const output = needsMeta
    ? `一共 ${rejected.length + 1} 行：**第一行是 report_meta**（上一份缺了它或者它写坏了），` +
      `之后一行一个 JSON，顺序和上面列出的顺序一致（第 1 块在第二行，第 2 块在第三行……）。` +
      `不要围栏，不要解释改了什么 —— 改动本身就是回答。`
    : `一行一个 JSON，**顺序和上面列出的顺序一致**（第 1 块在第一行，第 2 块在第二行……），` +
      `一共 ${rejected.length} 行。不要 report_meta，不要围栏，不要解释改了什么 —— 改动本身就是回答。`;
  return [
    `## 出口校验没过：下面这 ${rejected.length} 块要重写`,
    `报告的别的部分**已经过了**，一个字都不要动 —— 这一轮只重发下面列出的这几块。`,
    list,
    ...(general ? [`## 另外这几条是整份报告的问题\n\n${general}\n\n改的时候在上面那几块里就近处理，不要为它新增一块。`] : []),
    `## 输出\n\n${output}`,
  ].join("\n\n");
}

