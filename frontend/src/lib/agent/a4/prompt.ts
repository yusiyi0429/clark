/** 写报告要读的全套材料。各条链路各装一份，只有证据包和没核实的那几条不一样。 */
export type A4ReportInput = A4Input & {
  companyContext: string;
  cognitive: string;
  /** 证据包。空串表示这一轮没有台账，走 `a4ReportSystem(false)`。 */
  evidencePack: string;
  /** 没能核实的那几条，人话。 */
  unresolved: string;
};

/**
 * 写报告之前的**准备材料**：议题、预研、在版判断、公司上下文、证据包、
 * 没能核实的那几条、方法组那段认知。
 *
 * 单独抽出来是因为各条链路装的是同一套骨架：议题、预研、判断、公司上下文、认知段每一份
 * 一字不差，各自不同的只有自己那份证据包和自己没核实的那几条。两处各拼一次的话，
 * 几份原件之间会多出一处「谁多看到了一段材料」的差别，而那处差别在屏幕上看不出来 ——
 * 于是几份结论不一致时，那处不一致读起来像是模型的分歧，其实是装配的分歧。
 */
function a4ReportMaterialParts(input: A4ReportInput): string[] {
  const parts = [buildA4Material(input)];

  if (input.evidencePack.trim()) {
    parts.push(`## 本轮取回的证据包（外部事实只能从这里来）\n\n${input.evidencePack}`);
  }
  if (input.unresolved.trim()) {
    parts.push(
      `## 本轮没能核实的\n\n${input.unresolved}\n\n` +
        `这几条要单独成一节 \`## 未能核实的部分\` 照实写出来，并说清缺它会让哪个判断打几折。`
    );
  }

  const cognitive = input.cognitive.trim();
  if (cognitive) parts.push(`## 深度研究该怎么做\n\n${cognitive}`);

  return parts;
}

