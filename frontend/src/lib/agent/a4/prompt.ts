/**
 * 台账 → 递给 Writer 的证据包。
 *
 * **不给原始网页**（HP-1 的另一面）：给了它就会绕过引句去读上下文，然后写出引句撑不起
 * 的话。给的是引句本身、口径、档次和关系 —— 正好是写一句能被核的话所需要的全部。
 */
export function buildEvidencePack(entries: Evidence[]): string {
  if (!entries.length) return "";
  const rel: Record<string, string> = { supports: "支持", refutes: "反驳", qualifies: "限定" };
  return entries
    .map((e) => {
      const caliber = [
        e.value !== undefined ? `数值 ${e.value}${e.unit ?? ""}` : "",
        e.precision ? `口径 ${e.precision}` : "",
        e.period ? `期间 ${e.period}` : "",
        e.geography ? `地域 ${e.geography}` : "",
        e.usedAs === "historical_point" ? "用作历史序列上的一个点" : "",
      ]
        .filter(Boolean)
        .join("　");
      return [
        `${e.id}　【${rel[e.supportRelation] ?? e.supportRelation}　${e.sourceTier} 级　${e.sourceDomain}】`,
        `　说法：${e.claim}`,
        `　原文引句：「${e.excerpt}」`,
        caliber ? `　口径：${caliber}` : "",
      ]
        .filter(Boolean)
        .join("\n");
    })
    .join("\n\n");
}

/** 判定结果 → 「本轮没能核实的」那一段。 */
export function buildUnresolved(props: Proposition[], verdicts: Verdict[]): string {
  const byId = new Map(props.map((p) => [p.id, p]));
  const lines = verdicts
    .filter((v) => !v.ok)
    .map((v) => {
      const p = byId.get(v.propositionId);
      const why = terminalText(v) || v.unmet.join("；");
      /*
       * 不带命题编号。2026-09-05：ISS-208 那一轮成稿把「D1-P1、D2-P1…」当证据编号写进了正文，
       * 出口机检 A4-B06 判 p0 —— 编号是这里递给它的。命题只有原话，没有可引的号。
       */
      return `「${p?.statement ?? ""}」：${why}`;
    });
  return lines.join("\n");
}

