/**
 * 一轮深研的**墙上时间上限**，以及「这一步还来得及吗」这个问题的算法。
 *
 * ## 为什么要有一个上限
 *
 * 2026-08-27 那一轮（ISS-112）跑了 47 分钟还没出稿。链上每一步都是对的：四条维度链、每条
 * 最多三波、每波抓五页、每页各抽一次 —— 一次一个排着走，加起来最多 72 次串行调用，而实测
 * 单次抽取要 50 秒上下。**没有任何一处代码在算总时长**，所以它不会「超时」，只会一直跑。
 *
 * 一号位那边的口径很直接：这一步的产物是给人读的，过了那个点他已经去干别的了。所以时间
 * 是一档硬预算，和 token 额度一样 —— 不是「尽量快」，是「到点必须交东西出来」。那个点现在
 * 是 30 分钟（`DEFAULT_DEADLINE_MS`，一路从 20 抬上来的，每一次为什么抬记在它自己那里）。
 *
 * ## 到点交什么
 *
 * **交一份带缺陷清单的报告，不是交一个超时异常。** 这条和这个文件夹里所有「不过但往下走」
 * 的处置是同一条纪律（HP-5：查不到是合法结果）：少跑了一波检索、少写了一节，都记一句原话
 * 进 `gaps`，最后印在 `doc.sourceText` 文首那份清单里。少跑而不说的话，一份因为到点收口的
 * 报告和一份「外面就是没有材料」的报告在屏幕上长得一模一样。
 *
 * ## 这里只有两个动作
 *
 * `room()` 问「剩下的时间够不够开始这一步、并且给后面必须做的事留出位置」；`shedNote()`
 * 把「没开始」这件事写成一句人能读的话。**不排程、不预测、不抢占** —— 一个真正的调度器要
 * 知道每一步的实际耗时分布，而这条链上每一步的耗时取决于那一次模型想了多久，谁也不知道。
 * 所以只在每一步开始之前问一次，答案只有开始和不开始。
 */

/**
 * 默认 30 分钟。**这个数是一号位定的，不是算出来的**。所以它是需求，下面那张成本表要去
 * 凑它，不是反过来。
 *
 * ## 它三次没凑上，三次的修法都不一样
 *
 * 2026-08-27 第一次没凑上，改成了 25：那时 N0+N1+N2 要 9.3 分钟、成稿必须留 11.5 分钟，
 * 两头加起来就超过 20，取证那一段拿到的时间是负的。**那一次是把预算迁就了实现。**
 *
 * 2026-08-31 又没凑上：`RUN-A4-mth5jkf0-6`（ISS-118）出口对账 11 条 p0、该重写一稿，
 * 需要 690 秒而手上剩 641 秒，**差 49 秒**，那 11 条原样发了出去。当天先抬到了 40 分钟，
 * 然后发现那是同一个错误又犯一遍 —— 一遍顺利的运行按当时的估表就要 21.1 分钟，20 这个数
 * 从一开始就不可能达到。**那一次改的是实现**：N5 那几节从串行改成并发，`WRITE_PASS_MS`
 * 从 590 秒降到 410 秒，一遍顺利的运行落到 18.1 分钟，20 分钟第一次真的装得下。
 *
 * 2026-09-01 第三次没凑上，而这一次两头都得改。ISS-225 那两轮真运行（网宿 claude-opus-5
 * 主笔）撞上的是**换出口之后单次生成的时延翻了几倍**：下面那张表原来按 90 秒记一节，实测
 * 是 **423.4 秒**。20 分钟连写字那一段都装不下 ——
 *
 *   N5 出一稿：排结构 144 + 一节 423 + 收口 211（下界）  ＝ 778 秒，13.0 分钟
 *   前面四步：N0 46 + N1 232 + N2 180（撞单次上限）+ N4 55 ＝ 513 秒， 8.6 分钟
 *   两头合计 21.5 分钟，**一波取证都还没算**。
 *
 * 两轮都在 20 分钟上限上被砍：第二轮 6 节只写出 1 节，3 次 `a4.anchor-gate` 一次都没发出去。
 *
 * 实现这一头改的是**暖缓存换掉串行第一节**（`stage-write.ts`）：上一版拿一节 423 秒去换
 * 提示缓存，而实测那个缓存既没被写过（换网宿之后一个断点都没发出去）、就算写了也只活五
 * 分钟 —— 拿七分钟买一个五分钟后过期的东西。现在是一次几秒钟的极小调用把前缀写进去，各节
 * 一波并发去读。预算这一头改的就是这个 30：`WRITE_PASS_MS` 按新形状是 870 秒，一遍顺利的
 * 运行 27.3 分钟，25 装不下，30 装得下。
 *
 * ## 30 分钟里有什么、没有什么，以及余量有多薄
 *
 * 有：N0 主体卡、N1 草稿、N2 检索计划、至少一波取证、N4 对账、N5 整段出稿（暖缓存 + 排结构
 * + 各节一波并发 + 收口）、N6 出口对账，以及块一级的定点返修（`spliceRepair`，只重发被指名
 * 的那几个块）。
 *
 * 没有：**N6 打回之后的整稿重写**（那是又一遍对账加出稿，`WRITE_RESERVE_MS` 970 秒，合计
 * 43.4 分钟）；也没有第二波、第三波取证 —— 上面那 27.3 分钟只含一波。时间凑不出来的时候它
 * 会照实记一句进缺口清单 —— 这是有意的取舍：一份带缺陷清单的报告到点到手，好过一份完美的
 * 报告他已经不在了。要那一次重写就把 `TKOS_A4_DEADLINE_MS` 设成 2_610_000 上下。
 *
 * **余量是 165 秒，2.7 分钟，一成不到。** 拿它和这条链自己的抖动比一下就知道有多薄：这两轮
 * 之间单步差得最远的是排结构（144 对 27.7，差 116 秒），也就是说**一步跳一次这种量级的波动，
 * 余量就去掉七成**；一节从 425 涨到 590 就直接装不下。所以下一次「总在同一个地方收口」出现
 * 时，第一件事是回来重量这张表，不是接着抬这个数。
 */
const DEFAULT_DEADLINE_MS = 30 * 60_000;

/**
 * 这一轮给多少时间。`TKOS_A4_DEADLINE_MS` 能改 —— 测试要一个几秒的上限来验收口时的样子，
 * 而真跑不该为了测试把默认值改小。
 *
 * 读的时候算，不在模块求值期算：`v2On()` 同理，写死在常量上等于测试改不动它。
 */
export function deadlineMs(): number {
  const raw = Number.parseInt((process.env.TKOS_A4_DEADLINE_MS ?? "").trim(), 10);
  return Number.isFinite(raw) && raw > 0 ? raw : DEFAULT_DEADLINE_MS;
}

