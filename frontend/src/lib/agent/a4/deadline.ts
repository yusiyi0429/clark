/**
 * **三件事必须分得开**：这一轮的调用结束了没有、交出来的东西完整不完整、拿它能干什么。
 *
 * 上一版只有一个 `degraded: true` 和一个 `status: "ok"`。ISS-239 那一份：三节只有 S3 写成，
 * S1/S2 各在 420 秒上超时，收口补了一段摘要 —— 而屏幕上它是一份 `status=ok` 的报告，首屏
 * 直接进批准与拟制命令。**补一段摘要不等于补齐核心论证**，但那一版没有任何一栏说得出这
 * 件事。
 *
 * 这三栏就是为了让那件事在数据上留下痕迹，而不是靠读的人自己去数节数：
 *
 * · `callsFinished`：①「调用结束」。跟内容好坏无关。
 * · `completeness`：②「完整 / 部分 / 失败」。看的是**核心论证的成节数和收口**，不看字数。
 * · `readiness`：③「可供讨论 / 具备决策条件」。服务端的下达入口读的是这一栏 ——
 *   §3.D 那条「限制必须在服务端动作入口同样有效，不能只隐藏按钮」落在这里。
 *
 * `未知` 是给**旧报告**留的档。旧报告没有这一栏，读出来必须是「未知」，
 * **不许凭 `confidence` 猜成完整** —— 置信度说的是判断有多硬，不是报告写完了没有。
 */
export const DELIVERY_STATES = ["完整", "部分", "失败", "未知"] as const;
export type DeliveryState = (typeof DELIVERY_STATES)[number];

export const DECISION_READINESS = ["具备决策条件", "可供讨论", "不足以讨论", "未知"] as const;
export type DecisionReadiness = (typeof DECISION_READINESS)[number];

export type Delivery = {
  /** ① 这一轮的模型调用跑完了没有。`null` = 旧报告没记。 */
  callsFinished: boolean | null;
  /** ② 交付完整性。 */
  completeness: DeliveryState;
  /** ③ 拿它能干什么。 */
  readiness: DecisionReadiness;
  /**
   * 核心论证的成节数 / 计划节数。**补一段摘要不改这两个数** —— ISS-239 三节成一节、收口
   * 交了摘要，`{written:1, planned:3}` 加 `closing:true` 把那两件事分得开。
   */
  coreSections: { written: number; planned: number } | null;
  /** 收口那一次（核心判断横幅 + 最终判断）交了没有。 */
  closing: boolean | null;
  /** 落成这三档的理由，一条一句。屏幕上「为什么只是部分」读的就是它。 */
  why: string[];
};

/** 旧报告（和任何一份没记这一栏的东西）读出来的样子。 */
export const UNKNOWN_DELIVERY: Delivery = {
  callsFinished: null,
  completeness: "未知",
  readiness: "未知",
  coreSections: null,
  closing: null,
  why: ["这一份没有交付完整性记录（在这一栏之前生成的报告）"],
};

/**
 * 从落库的那份对象里读交付完整性。**只读 `delivery` 这一栏**。
 *
 * 不读 `confidence`、不读 `status`、不数块 —— 猜出来的「完整」比「未知」坏：前者会让服务端
 * 的下达入口放行一份没人验过的东西，后者只是让人再看一眼。
 */
export function readDelivery(raw: unknown): Delivery {
  if (!raw || typeof raw !== "object") return UNKNOWN_DELIVERY;
  const o = (raw as { delivery?: unknown }).delivery;
  if (!o || typeof o !== "object") return UNKNOWN_DELIVERY;
  const d = o as Record<string, unknown>;
  const completeness = (DELIVERY_STATES as readonly unknown[]).includes(d.completeness)
    ? (d.completeness as DeliveryState)
    : "未知";
  const readiness = (DECISION_READINESS as readonly unknown[]).includes(d.readiness)
    ? (d.readiness as DecisionReadiness)
    : "未知";
  const core = d.coreSections;
  return {
    callsFinished: typeof d.callsFinished === "boolean" ? d.callsFinished : null,
    completeness,
    readiness,
    coreSections:
      core && typeof core === "object" &&
      typeof (core as { written?: unknown }).written === "number" &&
      typeof (core as { planned?: unknown }).planned === "number"
        ? { written: (core as { written: number }).written, planned: (core as { planned: number }).planned }
        : null,
    closing: typeof d.closing === "boolean" ? d.closing : null,
    why: Array.isArray(d.why) ? d.why.filter((x): x is string => typeof x === "string") : [],
  };
}

/**
 * 「这一份能不能进批准入口」。**只有 `具备决策条件` 那一档为真。**
 *
 * 单独立一个函数而不是让各处各写一句 `=== "具备决策条件"`：服务端动作入口和页面按钮读的
 * 必须是同一句判断，各写一份的话总有一处会在加档的时候漏掉（`未知` 是最容易被写成 true 的
 * 那一档 —— 旧报告在页面上看着完全正常）。
 */
export const canDispatch = (d: Delivery): boolean => d.readiness === "具备决策条件";

/**
 * 「剩下的时间够开始这一步吗」。`need` 是这一步自己要的，`keep` 是后面必须做的那些要留的。
 *
 * 没有上限时（`msLeft` 是 `Infinity`）恒为真 —— 单测里那些不给 deadline 的 `new Harness`
 * 一行都不用改。
 */
export const room = (msLeft: number, need: number, keep = 0): boolean => msLeft >= need + keep;

/**
 * 「没开始」那句话。措辞在这里统一一次：同一件事在四个文件里各写一句会各说一套。
 *
 * 不足一分钟的上限按秒说 —— 真跑不会调到那个量级，但测试会，而「上限是 0 分钟」读起来
 * 像个 bug。
 */
export const shedNote = (what: string, msLeft: number): string => {
  const cap = deadlineMs();
  const capText = cap >= 60_000 ? `${Math.round(cap / 60_000)} 分钟` : `${Math.round(cap / 1000)} 秒`;
  return `${what} —— 这一轮的时间上限是 ${capText}，只剩 ${Math.max(
    0,
    Math.round(msLeft / 1000)
  )} 秒，按现状收口`;
};
