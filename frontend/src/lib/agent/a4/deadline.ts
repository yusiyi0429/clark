/**
 * 出一稿要多久：排结构 + 暖缓存 + 分节 + 收口 + 送检锚点。
 *
 * ## 为什么分节那一项是「一节」而不是「两节」，更不是「节数 × 一节」
 *
 * 大纲交回来的节数是三到六节（`prompt.ts` 的大纲要求），而这几节现在是**一波同时发出去**
 * 的（`stage-write.ts`，`SECTION_CONCURRENCY` 就是 6）。一波的墙上时间是最慢那一节的时间，
 * 不是它们的和 —— 所以这一项是 **1 × 一节**。
 *
 * 上一版这里是 `2 × 一节`：那时第一节要单独串行跑一趟，把提示缓存写进去，其余几节才并发去
 * 读。2026-09-01 实测把那个设计整个否掉了（换网宿之后一个断点都没发过，而且缓存只活五分钟、
 * 一节要跑七分钟），换成一次几秒钟的暖缓存调用 —— 于是那多出来的一整节变成了 `COST.warm`。
 *
 * 补写那一波（砸掉的那几节重来一次）**不进这个估值**：它是砸了才有的一波，由 `room()` 在
 * 跑的时候现问。七节以上要分两批也同理 —— 这张表要的是「后面还塞不塞得下」，按常态估、宁可
 * 估高一点点，比按最坏情形估更有用。
 *
 * 推出来是 145 + 20 + 425 + 240 + 2×20 ＝ **870 秒**（上一版 410 秒）。这一段翻倍是换出口
 * 之后单次生成时延翻了几倍的直接结果，不是这里多做了什么。
 *
 * N6 打回重写一稿用的就是这个数 —— 那一轮是**又一整遍 N5**，不是一次小修。
 */
export const WRITE_PASS_MS =
  COST.outline + COST.warm + COST.section + COST.closing + 2 * COST.anchorGate;

/** 从 N4 到交稿那一整段。N3 拿它当「后面要留的位置」。 */
export const WRITE_RESERVE_MS = COST.reconcile + WRITE_PASS_MS;

