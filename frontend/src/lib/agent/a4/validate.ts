/* 第一层：那份正式报告                                                        */
/* -------------------------------------------------------------------------- */

/**
 * 报告那一层的质量门。**全是 p1，一条都不挡。**
 *
 * 挡不住的原因是结构性的：重修循环喂的是压缩那一层的对话（见 `run.ts`），把报告的
 * 违规递进去，模型只会去改四节 —— 台账上违规消失了，报告一个字没动。所以这几条只
 * 记不修：它们的用处是让「这一版报告写歪了」在运营台上数得出来，而不是当场救回来。
 *
 * **不走 `commonViolations`。** 那边的 `MARKDOWN` 规则把 `^#{1,6}\s` 判成违规，而报告
 * 的小标题就是 `## ` —— 直接复用会让每一份合规的报告都报一条 FE-md。所以这里自己挑
 * 那几条（回避式措辞、空词、member: 死链、感叹号），markdown 单独数。
 */
export function validateReport(
  text: string,
  /**
   * 这一轮有没有真的入账过外部证据。**按台账条数传，不按「配没配 key」传** ——
   * 配了 key 但一页都没抓到的运行，手上和没配 key 一样是空的。
   */
  hasEvidence = false
): Violation[] {
  const v: Violation[] = [];
  const push = (rule: string, message: string) => v.push({ rule, severity: "p1", message });

  const body = (text ?? "").trim();
  if (!body) {
    push("A4-R01", "报告正文是空的 —— 这一份只有四节，没有可署名分发的原件。");
    return v;
  }

  const lines = body.split(/\r?\n/);
  const headings = lines
    .map((l) => /^##\s+(.*)$/.exec(l.trim()))
    .filter((m): m is RegExpExecArray => !!m)
    .map((m) => m[1].trim());

  // ---- 标题（第一行）----------------------------------------------------
  const title = (lines[0] ?? "").trim();
  if (/^#/.test(title)) {
    push("A4-R02", "第一行标题前面带了井号；标题不加记号，`## ` 只用于小标题。");
  }
  if (title && !/(不是|而非|而不是|并非|与其说)/.test(title)) {
    // 和四节那条 A4-05 同一个道理：只说「是什么」的标题读者没法反驳，也就没法确认。
    push("A4-R03", "标题没有排除任何一个错误答案，读起来是个分类名而不是一句判断。");
  }

  // ---- 该有的几节 --------------------------------------------------------
  const has = (kw: string) => headings.some((h) => h.includes(kw));
  if (!has("核心判断")) push("A4-R04", "没有「核心判断」这一节 —— 开篇即给答案是 §6.1 的硬要求。");
  if (!has("最终判断")) push("A4-R04", "没有「最终判断」这一节，报告没有回到标题那句话收口。");
  if (!has("决定性证据")) push("A4-R04", "没有「决定性证据」这一节，读的人无从核这几条判断。");
  if (!has("含义")) push("A4-R04", "没有「对我们的当前含义」这一节，研究没有落到公司身上。");

  /*
   * 观点型章节的条数。判据是小标题以「一、」这种序号开头 —— 那是提示词里给的写法，
   * 数它比数「这个标题是不是一句判断」可靠得多（后者不是确定性检查能回答的）。
   */
  const chapters = headings.filter((h) => /^[一二三四五六七八九十]+[、.．]/.test(h));
  if (chapters.length < 2) {
    push("A4-R05", `观点型章节只有 ${chapters.length} 节，少于 2 节；§6.2 要的是 2–5 节。`);
  } else if (chapters.length > 5) {
    push("A4-R05", `观点型章节有 ${chapters.length} 节，超过 5 节；再多就是在搬材料。`);
  }
  for (const h of chapters) {
    const stem = h.replace(/^[一二三四五六七八九十]+[、.．]\s*/, "");
    if (CATEGORY_HEAD.test(stem.replace(/[：:]$/, ""))) {
      push("A4-R06", `章节标题「${h}」是分类词不是判断 —— §6.2 要的是标题本身就是一条判断。`);
    }
  }

  // ---- 「本轮联没联网」这句话必须跟事实一致 -------------------------------
  /*
   * 两头都要查，因为两种说反了都在骗人。
   *
   * 没入账证据时缺这一句：外部来源看起来就和内部文档一样已经核过，而它们是模型的既有
   * 知识，本轮谁都没查。这一句不是免责，是让读的人知道哪几条在落地引用之前要先核一遍。
   *
   * 入账了证据却还写着「未联网」：这一版真的抓了页、逐字核过引句、绑了可点开的地址，
   * 而报告在自我否认。后果比前一种更糟 —— 读的人会把已经核过的那几条也当成待核，
   * 于是整份研究的可信度被抹平成同一档，取证那几步等于没做。
   */
  if (!hasEvidence && !/未联网/.test(body)) {
    push("A4-R07", "「决定性证据」里没写明外部来源本轮未联网核验 —— 读的人会当它们已经核过。");
  }
  if (hasEvidence && /未联网/.test(body)) {
    push("A4-R07", "这一轮真的联网取了证并入了账，报告里却写着「未联网」—— 那几条已核过的证据会跟着被当成待核。");
  }

  // ---- 记号：只允许 `## ` -------------------------------------------------
  if (/\*\*/.test(body)) push("A4-R08", "报告里有 `**` 加粗记号，屏幕按纯文本渲染，会原样显示成星号。");
  if (/^\s*[-*]\s/m.test(body)) push("A4-R08", "报告里有 `- ` 列表记号，会原样显示成横线。");
  if (/^\s*\d+[.)]\s/m.test(body)) push("A4-R08", "报告里有 `1. ` 编号列表记号，会原样显示。");
  if (/^\s*\|/m.test(body)) push("A4-R08", "报告里有表格，屏幕不渲染表格。");
  if (/^#(?!#\s)#{0,4}\s/m.test(body.split(/\r?\n/).slice(1).join("\n"))) {
    push("A4-R08", "报告里出现了 `## ` 以外的井号标题，屏幕只认 `## `。");
  }

  // ---- 措辞：借 rules.ts 的词表，但一律降到 p1 -----------------------------
  // 这一段提成了 `wordingViolations`，默认那条七步链收口时调的是同一份 —— 同一条规则在两支
  // 台账上必须是同一个规则名、同一句话，否则运营台按规则名分组时会把它算成两条。
  v.push(...wordingViolations(body));

  /*
   * 篇幅。**只有下限，没有上限**（补遗 §0：字符数不是 KPI，证据利用率才是）。
   *
   * 上限那一条删了。原来是 4000 字，配着提示词里「1800 到 3500 字」那句 —— 而一份用完了
   * 二十几条证据的报告本来就该长过它。留着上限的后果不是运营台上多亮一条 p1，是提示词
   * 那半句会一直逼着模型把材料丢掉：把证据用完这件事和「别超过 3500 字」直接冲突，而
   * 冲突里赢的总是那个能数出来的。
   *
   * 下限留着，理由和当初一样：一份太短的报告是取舍还没做完就交了。1500 这个数只是「一次
   * 都没展开」的下界，不是目标 —— 该有多长由手上有多少条证据决定，那一件由 A4-B11
   * （证据利用率）去管。
   */
  const n = chars(body);
  if (n < 1500) push("A4-R09", `报告 ${n} 字 —— 这个长度里没有一条判断被展开过，取舍还没做完就交了。`);

  return v;
}

/* -------------------------------------------------------------------------- */
/* 第二层：压出来的四节                                                        */
/* -------------------------------------------------------------------------- */

/** 四条分流之外的写法。「持续关注」不在四条里，而且它的真实含义是「我没想清楚」。 */
const ROUTE_WORDS = /(更新战略|改.{0,4}判断|立项|执行|取证|证据|关闭|收口|不再跟)/;

export function validateResearch(doc: ResearchDoc): Violation[] {
  const v: Violation[] = [];
  const push = (rule: string, severity: "p0" | "p1", message: string) =>
    v.push({ rule, severity, message });

  const j = doc.judgment ?? [];
  const e = doc.keyEvidence ?? [];
  const c = doc.counters ?? [];
  const u = doc.unknowns ?? [];

  // ---- 四节都必须有内容 -------------------------------------------------
  // A4-01：缺任何一节都不是「这次没查到」，是没按四节交。
  if (j.length < 2 || j.length > 4) push("A4-01", "p0", `当前判断应为 2–4 条，实际 ${j.length} 条。`);
  if (e.length < 3 || e.length > 6) push("A4-02", "p0", `关键 Evidence 应为 3–6 条，实际 ${e.length} 条。`);
  if (u.length < 2 || u.length > 4) push("A4-04", "p1", `不确定性应为 2–4 条，实际 ${u.length} 条。`);

  /*
   * A4-03 反证一条都没有 = p0。
   *
   * 这一条是整份东西的反谄媚保证。CQ101 §07 要求主动找反证，而模型的默认行为
   * 是把反证写成「当然也存在一定风险」。零条反证在数据上看起来很干净，实际是
   * 这份研究最危险的状态 —— 一号位会以为它已经被压力测试过了。
   */
  if (c.length === 0) {
    push("A4-03", "p0", "一条反证都没有。写不出能动摇自己判断的东西，说明没在找。");
  } else if (c.length > 4) {
    push("A4-03", "p1", `反证 ${c.length} 条，超过 4 条；挑最能推翻判断的那几条。`);
  }

  // ---- 溯源 -------------------------------------------------------------
  // A7-01：Evidence 和反证是要拿去核的，没有溯源就核不了。
  e.forEach((s, i) => {
    if (!traced(s)) push("A7-01", "p0", `第 ${i + 1} 条 Evidence 没有溯源。`);
  });
  c.forEach((s, i) => {
    if (!traced(s)) push("A7-01", "p0", `第 ${i + 1} 条反证没有溯源。`);
  });
  j.forEach((s, i) => {
    if (!traced(s)) push("A7-01", "p1", `第 ${i + 1} 条判断没有溯源。`);
  });

  // ---- 第一条判断要表态 --------------------------------------------------
  const first = j[0]?.text ?? "";
  if (first && !/(不是|而非|而不是|并非)/.test(first)) {
    // p1 而不是 p0：句式是手段不是目的，硬打回会让模型为了套句式而说废话。
    push("A4-05", "p1", "第一条判断没有排除任何一个错误答案；只说「是什么」的判断没法被反驳，也就没法被确认。");
  }

  // ---- 每条判断要落到「对我们意味着什么」---------------------------------
  j.forEach((s, i) => {
    if (!/(——|—|意味着|对我们|因此我们|我们应)/.test(s.text)) {
      push("A4-06", "p1", `第 ${i + 1} 条判断没有落到「对我们意味着什么」。`);
    }
  });

  // ---- 反证要写清推翻门槛 ------------------------------------------------
  c.forEach((s, i) => {
    if (!/(推翻|不成立|就足以|则.{0,6}判断|反转|失效)/.test(s.text)) {
      push("A4-07", "p0", `第 ${i + 1} 条反证没写清「成立到什么程度就足以推翻判断」——那是感想，不是反证。`);
    }
    /*
     * A4-13 反证不能是纯假设场景。
     *
     * 「若市场环境出现突变，则……」读起来很像反证，而且能满足上面那条门 ——
     * 但它是**编出来的情景**，不是已知的、指向相反方向的事实。两者混在一起，
     * 一号位就分不清哪些是真有问题、哪些只是想象出来的风险，于是会去防一个
     * 不存在的东西。判据：以「若/如果/一旦」开头，且唯一的溯源是自己的推断。
     */
    const conditional = /^(若|如果|一旦|假如|倘若)/.test(s.text.trim());
    const onlyGuess = (s.traces ?? []).every((t) => t.kind === "agent");
    if (conditional && onlyGuess) {
      push(
        "A4-13",
        "p0",
        `第 ${i + 1} 条反证是一个假设情景，不是已知事实 —— 它属于「不确定性」。反证要有外部或内部依据。`
      );
    }
  });

  // ---- 不确定性要写清谁能答 ----------------------------------------------
  u.forEach((s, i) => {
    if (!/(能回答|才能回答|需要|由.{1,12}(给|出|提供)|问)/.test(s.text)) {
      push("A4-08", "p1", `第 ${i + 1} 条不确定性没写清谁能回答或要什么材料。`);
    }
  });

  // ---- 分类式开头 --------------------------------------------------------
  [...e, ...j].forEach((s, i) => {
    const head = s.text.split(/[，。：:]/)[0] ?? "";
    if (CATEGORY_HEAD.test(head)) {
      push("A4-09", "p1", `第 ${i + 1} 条以分类词「${head}」开头，应该直接写 synthesis。`);
    }
  });

  // ---- 建议分流 ----------------------------------------------------------
  const r = doc.routeSuggestion ?? "";
  if (!r.trim()) push("A4-10", "p0", "没有建议分流。");
  else {
    if (!ROUTE_WORDS.test(r)) {
      push("A4-10", "p0", "建议分流没有落在四条路之一（更新战略 / 立项执行 / 取证再议 / 关闭）。");
    }
    if (!/(因为|理由|由于|所以)/.test(r)) {
      push("A4-11", "p1", "建议分流没说明为什么是这条而不是相邻那条。");
    }
    if (sentences(r).length > 3) push("A4-11", "p1", "建议分流超过三句；它是一行，不是一段。");
  }

  // ---- 全局 --------------------------------------------------------------
  const all = [
    ...j.map((x) => x.text),
    ...e.map((x) => x.text),
    ...c.map((x) => x.text),
    ...u.map((x) => x.text),
    r,
  ].join("\n");
  v.push(...commonViolations(all, "深研"));
  v.push(...overclaim(all, "深研"));

  /*
   * A4-12 篇幅。深研比预研厚，但它仍然不是那份一万三千字的原始报告 ——
   * 这四节是**读完原始材料之后的取舍结果**，长度本身就是取舍做没做的证据。
   */
  const total = chars(all);
  if (total > 2600) push("A4-12", "p1", `全文 ${total} 字，超过 2600 —— 四节是取舍的结果，不是把材料搬过来。`);
  if (total < 500) push("A4-12", "p1", `全文只有 ${total} 字，薄到不像做过深研。`);

  return v;
}
