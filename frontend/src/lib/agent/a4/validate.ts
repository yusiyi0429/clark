/**
 * A4 Deep Research 的确定性质量门。**不调模型。**
 *
 * 规则来自 tkos_quality_rubric_v0.1.yaml 的 A4 组里 kind=deterministic 的那些。
 * 判断性的（「这条反证是不是真的反证」「这个判断是不是可证伪」）不在这里 ——
 * 那些交给反证复核那一遍去冲，见 prompt.ts 的 A4_CHALLENGE_SYSTEM。
 *
 * 这一层只回答一个问题：**这份东西的形状对不对。**
 *
 * 两个门，对着两层交付：`validateReport` 数那份正式报告，`validateResearch` 数
 * 压出来的四节。
 *
 * ## 这两个门只在 `TKOS_DR_V2=0` 那条对照链上跑 —— 这是有意的，不是漏接
 *
 * `runDeepResearch` 第一句就按 `v2On()` 转给 `pipeline.ts`（`run.ts:548`，**默认转**），
 * 而调这两个门的地方全在那一句下面（`run.ts:1327` / `:1421`）。所以默认那条七步链上，
 * 这个文件一行都不跑。查到这里的人第一反应会是「接上去」，先读完下面两段再动手。
 *
 * **默认那条链有自己的三层门，各管一段**：`blocks/lint.ts`（A4-B01…B11，每个块的结构
 * 纪律）、`gate.ts`（A4-G01…G06，引用绑不绑得上、算术复不复算得通）、`audit.ts`
 * （A4-N01…N07，这一轮的研究链有没有断）。下面这两个门里能转过去的，那边都已经有人管：
 *
 *   · A4-R01（正文是空的）→ A4-B01「一个块都没有」
 *   · A4-R04（该有的几节）→ A4-B01（verdict_banner / judgment / falsify_card / evidence_list
 *     都是必交块）＋ A4-N07（`layerGaps` 数正文自不自足）
 *   · A4-R07（本轮联没联网这句话）→ `no-evidence.ts` 折出的那一栏 ＋ A4-G04（有命题没闭合
 *     就必须有「未能核实」那一节）
 *   · A7-01（每条 Evidence 要有溯源）→ A4-B02 / A4-B03（数字和判断都要 `evidenceRefs`）
 *     ＋ A4-B06（引了就要解析得开）
 *   · A4-02 / A4-12（关键证据几条、四节多长）→ A4-B11（证据利用率：取回来的每一条要么写进
 *     正文、要么在 `evidence_usage` 里带着弃用理由）
 *
 * **转不过去的分两类。** 一类是**只对散文那种形状成立**的：A4-R02（首行别加井号）、A4-R08
 * （别用 markdown 记号）、A4-R05 / A4-R06（观点型章节的条数与标题写法，判据是「一、」这种
 * 序号）—— 块那一侧标题是 `report_meta` 的一栏数据、小节是块的 `heading`，这几条搬过去
 * 只会给每一份合规的报告记一串假违规。另一类是**措辞那一小组**（回避式措辞、空词、
 * `member:` 死链、感叹号、无依据的绝对化）：它们和交付形状无关，两支都该数 —— 已经提成
 * 下面的 `wordingViolations`，`pipeline.ts` 收口那一句也调它。
 *
 * ## `validateResearch` 不许接到默认那条链上
 *
 * 那一支的四节**不是模型写的**：`pipeline.ts` 的 `foldSections` 按块的类型直接折
 * （`verdict_banner` ＋ `judgment` 是判断，证据清单是关键证据，`falsify_card` 是反面，
 * `unverified_panel` 是未知）。拿这个门去数它，数的是我们自己那段折叠代码，不是模型的产物。
 *
 * 最硬的一条是 A4-10：折出来的 `routeSuggestion` 是一句机器话（「这一轮机检落在「…」这一档，
 * 报告原文在原件页签里。」），`ROUTE_WORDS` 一个词都不命中 —— 接上去等于**每一轮都多一条
 * p0**，于是每一份报告都被标成 degraded，运营台上「哪一轮真的有问题」这件事当场作废。
 * 要让四节这一层在默认链上也有门，该做的是给 `foldSections` 补一条能落到四条分流之一的
 * 建议，不是把这个门直接挂上去。
 */
import type { ResearchDoc, Statement } from "@/lib/data/types";
import {
  BUZZ,
  CATEGORY_HEAD,
  chars,
  commonViolations,
  HEDGES,
  overclaim,
  sentences,
  type Violation,
} from "@/lib/agent/rules";

export type { Violation } from "@/lib/agent/rules";
export { blocking, summarize } from "@/lib/agent/rules";

const traced = (s: Statement) => Array.isArray(s.traces) && s.traces.length > 0;

/**
 * 一份深研报告正文里的措辞违规。**两支深研都调它。**
 *
 * 提出来是因为这一小组和交付形状无关：块也好散文也好，「机会与挑战并存」都是说了等于没说，
 * `member:xxx` 都是一枚点不开的编号。上面文件头列的那几条转不过去的规则里，只有这一组是
 * 默认那条七步链**本该数而一直没数**的 —— 它那三层门（`blocks/lint.ts` / `gate.ts` /
 * `audit.ts`）一条都没覆盖到词面：A4-N01 是唯一沾边的一条，而它只扫 `verdict_banner`
 * 一个块，用的还是 `draft.ts` 自己那张更短的回避词表。
 *
 * **不走 `commonViolations`，而且一律 p1。** 不走的原因见 `validateReport` 的注释（那边的
 * `MARKDOWN` 规则会把每一份合规报告的 `## ` 小标题判成违规）；降成 p1 的原因是这一组挡不住
 * 也不该挡：措辞是重写一整稿才改得动的东西，而两支的重写轮都是按块（或按四节）打回的，
 * 报一条 p0 只会换来一轮改不到点子上的返修。它们的用处是让「这一版写歪了」在运营台上数得出来。
 */
export function wordingViolations(text: string): Violation[] {
  const v: Violation[] = [];
  const push = (rule: string, message: string) => v.push({ rule, severity: "p1" as const, message });

  const body = (text ?? "").trim();
  if (!body) return v;

  for (const h of HEDGES) if (body.includes(h)) push("G-08", `报告里出现回避式措辞「${h}」。`);
  for (const b of BUZZ) if (body.includes(b)) push("G-09", `报告里出现空词「${b}」。`);
  if (/member:[A-Za-z0-9_-]+/.test(body)) {
    push("A7-03", "报告里出现本体内部编号 member:xxx —— 屏幕认不出、点不开。");
  }
  if (/[！]/.test(body)) push("G-10", "报告里有感叹号。");
  v.push(...overclaim(body, "深研报告").map((x) => ({ ...x, severity: "p1" as const })));

  return v;
}

