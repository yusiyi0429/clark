/**
 * 把模型给的一段字摆成屏幕上那个样子。**这一层只改格式，不改内容。**
 *
 * 为什么它不写在 prompt 里：句数、块数、字数这些可数的东西 `rules.ts` 已经在数了
 * （数不对就打回重生成）；而「星号要不要出现」「中英文之间有没有空格」「小标题叫
 * 什么」这几件事**连数都不用数** —— 它们有唯一正确答案，交给模型只是每一轮重赌
 * 一次，赌输了要么屏幕上多两个星号，要么白烧一轮重试。
 *
 * 所以分工是：prompt 负责把内容问出来（观点、边界、来源），这一层负责把它摆成
 * 屏幕上那个形状。
 *
 * ## 它故意只用在 A1a 那份 issue framing 上
 *
 * 不在 `toStatements()` 里顺手做 —— 那条路 A3/A4/A5 都走，而那三个 agent 的
 * `validate.ts` 里有 `FE-md`（markdown 记号）这条 p0。在校验之前把星号洗掉，那条
 * 质量门就再也不会红，而它数的东西并没有变好，只是看不见了。质量门测的是模型交出来
 * 的形状对不对，把它悄悄改对是这套东西里最贵的一种自欺。
 *
 * A1a 的 issue framing 是新加的字段组，那边没有对应的确定性门（`checks.ts` 是只记不
 * 挡的自检，而且它读的是模型**原样**给的 `out`，看得见星号）—— 所以在那里洗是安全的。
 */

/** 汉字。不含中文标点（「」，。（）都在别的区段），所以下面加空格时不会误伤标点。 */
const CJK = "㐀-䶿一-鿿";

/**
 * 模型照着技能文档抄下来的块名。
 *
 * 技能里的 Output Contract 是文本块（`Sharp Title：` 那种），落到这个系统里是 JSON
 * 字段 —— 于是模型常常两样都给：字段名对了，值的开头又把块名抄了一遍。它是格式不是
 * 内容，屏幕自己有小标题（见 `a1a/framing.ts` 的 `framingBlocks`），留着就会出现
 * 「发生了什么：发生了什么：…」。
 */
const ECHOED_LABEL =
  /^\s*(sharp\s*title|potential\s*issue\s*statement|what\s*happened|implication|source|evidence\s*boundary|情况描述|核心观点|发生了什么|这意味着什么|来源|出处|证据边界|真正需要回答的问题|真正要回答的问题)\s*[：:]\s*/i;

/**
 * 一段字的纯文本整形。
 *
 * 非字符串（模型给了数组 / null / 数字）一律返回空串：调用方靠空串判「这一段没给」，
 * 而 `String(null)` 会变成一个写着 null 的段落摆到一号位面前。
 */
export function plain(raw: unknown): string {
  if (typeof raw !== "string") return "";
  let s = raw.trim();
  if (!s) return "";

  s = s.replace(ECHOED_LABEL, "");

  // markdown 记号。屏幕按纯文本渲染（`AgentText` 只按空行分段），留着就原样显示成
  // 星号井号 —— 而技能文档本身是 markdown 写的，模型跟着写是默认行为。
  s = s
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/\*(.+?)\*/g, "$1")
    .replace(/(^|\n)[ \t]{0,3}#{1,6}[ \t]*/g, "$1")
    .replace(/(^|\n)[ \t]{0,3}[-*•][ \t]+/g, "$1")
    .replace(/`/g, "");

  // 引号一律「」。输出是 JSON，裸的 ASCII 双引号在生成时就有一半概率把它弄坏；
  // 弄不坏的那一半会带着一对直引号出现在正文里，和屏幕上其余文字不是一套。
  s = s
    .replace(/"([^"\n]{1,120})"/g, "「$1」")
    .replace(/[“”]([^“”\n]{1,120})[“”]/g, "「$1」");

  // 中英文与数字之间加空格：写「产品 1.0」「AI Agent 走向组织化」。屏幕上其余文字
  // 都是这个排版，不一致会很显眼，而这件事模型每段都要重赌一次。
  s = s
    .replace(new RegExp(`([${CJK}])([A-Za-z0-9])`, "g"), "$1 $2")
    .replace(new RegExp(`([A-Za-z0-9])([${CJK}])`, "g"), "$1 $2");

  // 行内的多余空白收掉；段落之间那一个空行留着 —— `AgentText` 按它分段。
  s = s.replace(/[ \t]{2,}/g, " ").replace(/[ \t]+\n/g, "\n").replace(/\n{3,}/g, "\n\n");

  return s.trim();
}

/**
 * 让一句话以句末标点收尾。
 *
 * 用在**被当成小标题的那一句**上（S02 每条依据前面那个判断式短标题）：模型给
 * `label` 时一半带句号一半不带，而屏幕要把它加粗接在正文前面 —— 不带的那一半读起来
 * 是「瓶颈正在换层 NEC 全 AI 部门的核心创新不是…」，两句黏成一句。
 *
 * 不补感叹号：`rules.ts` 的 G-10 本来就在挡它。
 */
export const asSentence = (s: string): string =>
  s && !/[。？！.?!：:]$/.test(s) ? `${s}。` : s;
