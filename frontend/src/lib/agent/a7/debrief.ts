/**
 * A7 —— 会后提炼。**一场会的录音转成的字进来，按议题拆成一份会后的样子。**
 *
 * ## 为什么产出的单位是「议题」，不是「会」
 *
 * 一场战略会上过三件议题，产出一份三千字的纪要，是这条路最容易走上的那条 —— 也是最没
 * 用的那条：一号位第二天早上要决定的是**这一件**事下一步怎么走，而他拿到的是一份混着
 * 另外两件事的文档，得先自己拆一遍。拆的这一下正是这个 agent 存在的全部理由。
 *
 * 所以输出是一个数组，一件议题一份，每份只说自己那一件。哪一句归哪一件由模型判 ——
 * 那是语义问题，关键词匹配换个说法就漏（同 `a6/extract.ts` 开头那段）。
 *
 * ## 为什么产出不再只是「要点 + 待办」
 *
 * 上一版交的是两样：`points` 和 `todos`。真按一份人写的复盘对了一遍之后，那两样**不够
 * 用**，缺的三样各自都能让这张卡骗人：
 *
 *   · **没有第一行。** 五条摊在卡面上，他得读完五条才知道这场会到底把这件事推没推
 *     动。人写的复盘第一段永远是一句「核心观点」——「讨论焦点已从『要做一套什么系统』
 *     推进到灯塔项目如何证明一号位价值」—— 一句话就是这场会的位移，读完它才决定要不要
 *     往下读。所以有了 `summary`，它是卡面上的第一行。
 *   · **每条都没有到头的地方。** 一件事单独摆着，下一次就会被做得比会上说的更宽。人写
 *     的那张表第三列写的是「约七成至八成为会议中的价值判断，尚未转化为报价模型」——
 *     一件事和它管到哪儿必须贴在一起，分家之后读的人得自己对回去。所以 `boundary`
 *     跟着每一条走，而不是并成另一段。
 *   · **没定的事看不见。** 这是最危险的一样：一份读起来样样都定了的纪要，会让人以为
 *     共识已经达成，而实际上「目标客户选择」「收费结构」「首版边界」全悬着。压缩最先
 *     丢的恰恰是这一段（它读起来最像「还没有内容」）。所以 `open` 是独立的一样，而且
 *     `consensus` 单独判一次「这场会到底谈拢了没有」。
 *
 * ## 为什么 `points` 装的是任务，不是会上定下来的要点
 *
 * 这一段起初交的是几条结论 ——「定价应按贡献设计」「首版要端到端成立」。按一号位在那
 * 张卡上真正的动作对了一遍之后，那是**读完就没有下一步**的东西：他在卡上按下的那颗
 * 键，含义是「这件议题就此进入已部署」，而一叠结论被部署下去，等于什么都没有被部署 ——
 * 他确认完还得自己再想一遍明天要做什么，而那一下正是这个 agent 该替他做完的。
 *
 * 所以这一段现在装的是**会上达成共识、接下来要部署下去的事**：一条一件，动词开头，说清
 * 交付物或判据。「定价应按贡献设计」是会上的结论，「按一号位获得的判断支持出一版分三档
 * 的报价模型」才是能被部署的那一件。
 *
 * `boundary` 跟着改口径：从「这条结论管到哪儿」变成「这件事到哪儿为止、不包含什么」。
 * 它存在的理由一个字没变 —— 变的只是被划边界的那个东西。
 *
 * `todos` 因此退回它本来的位置：**会上当场落到某个人身上的那句原话的记录**（「小张，你
 * 周五之前出一版」）。它和 `points` 不在同一层 —— 一个是这件议题要做成的事、等他确认，
 * 一个是会上已经派出去的动作、记下来而已。所以两段不该互相抄。
 *
 * ## 负责人这一栏，提炼这一步一个字都不填
 *
 * 数据层给每条任务留了一格 `assignee`，那一格**只有一号位在卡上点过那一下才有**。
 * 会上点没点名，模型只能从转写里猜，而这条链路能犯的最坏的错就是把一件事安到一个没接过
 * 它的人头上 —— 屏幕上那一行和他自己点过的长得一模一样，而那个人根本不知道。
 *
 * ## 三条不许越过的线
 *
 * 这三条是 AI 会议纪要最常见的三种事故，全部发生在同一个地方：**把没发生的事写成
 * 发生了**。
 *
 *   1. **不许编负责人。** 任务里一个人名都不出现（理由在上一节）；`todos[].owner` 只在
 *      会上真点了名时才填。一条挂着错人名的待办比一条没有负责人的待办坏得多 —— 后者
 *      他一眼看得出要补，前者他会直接发出去。
 *   2. **不许编期限。** 同上。「尽快」不是期限，不要把它折成一个日期。
 *   3. **讨论过 ≠ 决定了。** 会上没定的事进 `open`（照实说「没定」），不进任务 —— 进了
 *      任务，他一确认就把一件还没谈拢的事变成了公司要往下做的事。
 *
 * `boundary` 是第四条同源的线：**会上没划出边界，就没有这个字段。**替它编一个边界，等于
 * 替这场会加了一句没人说过的限制 —— 而那句话读起来和真的一模一样。
 *
 * 一件议题没谈出任何要往下做的事是**正常结果**，不是提炼失败。宁可交一份「任务两条、
 * 待办零条」，也不要为了让屏幕好看凑一条。
 *
 * ## 为什么是 pro 档，尽管它看起来只是一次摘录
 *
 * 第一版写的是 `flash`，理由是「摘录不是判断，压短用不着高档模型」。**真跑两轮之后
 * 那个理由不成立**：
 *
 *   · 一场只谈一件事的会，`flash` 交得很好 —— 人名、期限、谁反对，一条不落。
 *   · 换成一场过两件事、其中一件带转折的会（「中小尺寸在下行，车载和 IT 在涨」），
 *     它把方向**说反了**，写成「中小尺寸确实在涨」；同一轮里还把「孙姐，你下周二之前」
 *     里的人和期限一起丢了。
 *
 * 方向说反是这条链路能犯的最坏的错：那句话读起来完全通顺，他扫一眼就认了，而认下来的
 * 是一个和会上相反的结论。这不是「摘录」的难度，是**在一段有转折的话里认出谁修饰谁**
 * 的难度 —— 而那正是档位换得来的东西。加上 `summary` 和 `consensus` 之后这个理由只有
 * 更硬：两样都要求读完整场会再给一句判断，而不是把某一段压短。
 *
 * 代价可以接受：这一次调用**一场会只跑一次**（不是每轮对话都跑，那是 A6 的处境），
 * 转写几千到几万字，一天几次。
 *
 * ## 不开公司上下文
 *
 * 材料就是那份录音的文字，全在提示词里。开一次上下文是两跳加一次装配，换不到任何
 * 判准上的改善（同 A6，理由写在 `graphknowledge/lookup.ts` 那张表上）。
 */
