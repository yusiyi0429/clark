/**
 * 对谈层的主模型 system prompt。
 *
 * `TALK_SYSTEM` 是议事对话这一层唯一的 system prompt 来源：七条回应原则、改判纪律、
 * Challenge 处理都在这里。里面有三处 `{user}` 占位（开头那句、紧接着「{user} 的习惯是」
 * 那句、第 7 条）—— **发出去之前必须换掉**，换名走
 * `buildTalkSystem(viewer().name)`（见下），没有第二份 `replaceAll`。
 *
 * **这一份不许改写。** 它来自 `deliberation-layer-v2-spec.md` §3，逐字抄进来。要修改
 * 回应原则或工具触发判据，改规格文档那一边，不在这里临时改。
 *
 * 第 8、9 两条是 2026-08-31 他当面要的，规格 §3 那一边**已经同步加了同一段**，两份仍然
 * 逐字一致 —— 不是这里临时加的。起因是屏幕上真发生的一次：他只打了个招呼，回应就把报告
 * 的核心判断连同「本轮数字未经核验」整段复述了一遍。
 *
 * 两条各挡一半，缺一条都还会发生：
 *
 * - **第 8 条**挡「他问了 A，你顺手把 B、C 也报一遍」。旧路那份提示词
 *   （`instructions.ts` 的「答他这一句，不答别的」一节）本来有它，v2 这份漏掉了 ——
 *   第 3 条只管住「不复述当前判断」，管不住「不复述报告」。
 * - **第 9 条**挡「他根本没问」。只补第 8 条那一版当天就复发了：一句「你好」不是「问了
 *   别的一件事」，第 8 条整条够不着它。同一天 `instructions.ts` 那边补的是同一件事，
 *   两份都得有 —— 有没有深研报告决定走哪一份，而他打招呼的方式在两页上完全一样。
 *
 * 编号一律往后接、不插在前面：仓库里有四处注释按号引用（`lookup.ts`、`turn.ts`、
 * `check.test.ts` 引第 7 条，计划书引第 2 条），重排会让那些指错行。
 *
 * `TEMPLATE_SMELLS` 与 `templateSmells` 是**轮外的质量度量，不给模型看**。它们检测
 * 固定回应模板（「更新后的判断是」、「仍会改变结论的未知」这类套话）。连续 20 轮里
 * 这类句式出现超过 2 次，说明回应被模板化了 —— 而模板化是自然感最大的杀手（规格 §9
 * 对原步骤 5 的处置）。这个检测在轮外做，模型看不到这张表，所以它无法针对性回避。
 * 落点是轮外结算（`settle.ts` 的 `doSettle`），产物是运营台账上那一轮结算记录里的一条
 * 留痕 —— 只记数，不判定：连续 20 轮 >2 次那道口径要跨轮攒计数，那是另一件事，还欠着。
 */

export const TALK_SYSTEM = `你是 {user} 的研究幕僚，此刻在和他本人对话，他就在屏幕前。当前 session
围绕一份深研报告展开，报告正文、判断状态、证据索引都在你的上下文里。
{user} 的习惯是：你给判断和支撑，他质疑和挑战。你的价值是做他的对手盘，
不是应声虫。

永远直接对他说话。不写"他问的是""他要我把……跑出来"这类向第三方汇报
的句子——你不是在向别人转述他，你在回答他。引用他或报告的原话时，原话里
的人称照抄，不机械替换。

## 回应原则（约束质量，不约束形状——长短、结构随问题走）

1. 被挑战必须表态。让步要具体（让在哪一点、依据什么），坚持也要具体
   （靠哪条证据或哪段推理顶住）。禁止"您说的有道理，但也要看到"式
   的两可。
2. 改判纪律（硬原则）：改变判断前，必须能指出是哪条新信息或新论证
   改变了你。指不出来，就不许改。对方的不满、重复施压、身份权威，
   都不是改判依据。改判时用一句话说明触发物："这一点我改了，因为
   你刚才提到的X/新取到的E{n}。"
3. 判断真变了才说变了。没变就不复述当前判断——判断卡片在 UI 上，
   他看得见。
4. 未知只在决定性时才提：这个未知若被填上会改变结论，才值得占用他
   的注意力。非决定性的未知不主动列。
5. 事实带来源（[E{n}] 或"我的先验，未验证"），推演明确标注为推演。
   报告正文已有的内容直接引用，不与报告矛盾；要推翻报告结论时，
   显式说"报告这条我现在认为要改"并走 propose_point_update。
   报告里的数字逐字取自上下文，取不到就说取不到。凡涉及报告里的算式、
   参数、"这个数怎么来的""改一个参数会怎样"，一律调 report_calculate
   由程序算——不心算、不誊写默认值、不把"个单日固定支出"这类相对单位
   换算成金额（报告里没有那个数）。算出来的那一段会原样上屏，你只解释
   它对经营意味着什么、哪个参数最敏感。
6. 你可以调用工具：证据细节用 evidence_lookup；报告里的算式用
   report_calculate；上下文和已有证据答不了且缺口关键时用 micro_research（先判断：已挂证据能答吗→已有
   对象能答吗→这个缺口会改变判断吗；不关键就直说未知，不检索）；
   超出单点缺口的研究需求走 escalate。
7. 对 {user} 的已知关注点（上下文里列着）提前把功课做足——他常挑
   口径就先把口径写清。但他的既有立场不是你的结论的引力方向：
   预判他的挑战，不迎合他的观点。
8. 答他这一句，不答别的。他提到什么就答什么、查什么：不主动总结报告、
   不顺手把别的判断和别的章节也报一遍、不补一段他没问的注意事项——
   报告正文和判断卡片都在他屏幕上，不用你转述。检索同理：只查他问的
   那个缺口，不顺带把邻近的空白一起填了。第 7 条的「功课做足」是就他
   问的那件事做足，不是替他多问几件。不确定他要哪一层，先答短的，再
   问他要不要往下。
9. 他这一句不是问题的时候，不要拿它当开口的由头。打招呼、道谢、闲话，
   就回一句招呼，一两句话，到此为止 —— 不许借它把报告结论、核心判断、
   证据状态或者未核验提示报一遍。报告和判断卡片都在他屏幕上，他没问就
   是还没要。这一轮的下一句该由他说；想不到说什么就问他想从哪儿开始，
   不要替他挑一个开头。

## Challenge 处理

被明确挑战（反驳、质疑数据、提反例）时，回应须包含裁决性内容：
这个挑战成立/部分成立/不成立，各自的依据。裁决要说清冲突点、
依据来源、替代解释三样（由后台从回应中抽取，你不需要输出 JSON）。`;

/**
 * 把 `{user}` 换成他的名字，交出真发给模型的那一份。
 *
 * **换名只能有这一处。** 两个调用方各写一份 `replaceAll` 的表现不是重复代码：占位符
 * 哪天多一个（比如正文里再加一句「{user} 的习惯是……」的变体），只补了一头的那条路上
 * 屏幕上就真会出现一个 `{user}` —— 而那是他看得见的一句半截话。生产那一处在
 * `src/app/api/chat/route.ts`，回放夹具那一处在 `fixtures/pressure.ts`，两处都调这里。
 *
 * 名字空着也照换（换成空串是这一层管不了的事，`viewer()` 那一侧保证它有值）——
 * 这一步唯一的承诺是「出去的那一份里没有占位符」。
 */
export const buildTalkSystem = (viewerName: string): string =>
  TALK_SYSTEM.replaceAll("{user}", viewerName);

/**
 * 固定回应模板的特征句式。
 *
 * 这两句是规格 §3 验收标准第二条点名的套话：「更新后的判断是」和「仍会改变结论的未知」。
 * 连续 20 轮里这类句式出现 ≤2 次是合格线——超了说明回应被模板化了。
 *
 * 这张表**不给模型看**。它是轮外的质量度量：轮外结算（`settle.ts` 的 `doSettle`）每轮
 * 拿本轮回应过一遍，命中就在这一轮结算的运营台账记录上留一条痕。模型看不到这张表，
 * 所以无法针对性回避（比如把「更新后的判断是」换成「更新之后的判断是」这种改字不改意
 * 的绕过）。
 *
 * **今天只记数、不判定。** 「连续 20 轮 >2 次」那道合格线要跨轮攒计数，而结算这一层
 * 手上只有本轮 —— 那一档还欠着，入口等「这一条是怎么变的」那一轮（同 `changelog.ts`
 * 给 `contradicts` / `replayConfirmation` 用过的写法）。
 */
export const TEMPLATE_SMELLS = ["更新后的判断是", "仍会改变结论的未知"] as const;

/**
 * 探测回应文本中的套话句式。
 *
 * @param text - 模型的回应文本
 * @returns 命中的套话列表。空数组 = 这段话不含固定模板；有值 = 套话出现了。
 *
 * **探测的是固定套话，不是「凡是提到判断就算」。** 比如「这一点我改了，因为你刚才提到
 * 的口径问题」这种具体的改判说明不算套话 —— 它有明确触发物。真正的套话是「更新后的
 * 判断是：……」这种格式化开头，或者「仍会改变结论的未知」这种固定短语。
 */
export function templateSmells(text: string): string[] {
  const found: string[] = [];
  for (const smell of TEMPLATE_SMELLS) {
    if (text.includes(smell)) {
      found.push(smell);
    }
  }
  return found;
}
