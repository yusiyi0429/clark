/**
 * 运行模式。**这是 demo 版与 MVP 版之间唯一的一道缝。**
 *
 * 一个仓库、一次构建、一个开关。分支或者第二个仓库看起来更干净，代价是两边会各自
 * 长出对方没有的修复 —— 而演示前一天发现的那个 bug，永远是在另一边修的。
 *
 * ## 为什么默认是 `live`
 *
 * 原来默认是 `demo`（`TKOS_MODE !== "live"`）—— 那是这一版只用来演示的时候。现在
 * 这套东西要给词元云集的一号位真用，那个方向就反了：漏配一个环境变量的后果不是报错，
 * 是他对着为另一场准备的内容做判断。
 *
 * 那一档的内容不是编的（每个字都来自那八份 Word 包，见 `seed-demo.ts`），但它是**王总
 * 那一场**：读者是董事长层、三块生意里有两块不是词元云集，时间停在 7 月 15 日，而且
 * 预研、深研、判断板全是包里的原文 —— 那一档一次模型都不叫。屏幕上没有一处说这些。
 * 所以看上去就是「我的 Agent 今天研究出来的」。
 *
 * 所以默认给真数据。要看演示内容包，明确写 `TKOS_MODE=demo` —— 那是一个有人按下
 * 去的动作，而不是一次遗忘的结果。
 *
 * ## 为什么单独一个文件
 *
 * `/api/health` 要报出「这台跑的是真实数据还是示例数据」，而它是无副作用的存活探针，
 * 不能 import `store.ts`（那会把整个对象库初始化起来）。两处各自读一遍 `process.env`
 * 的话，哪天一处开始认 `"live"` 而另一处认非 `"demo"`，健康检查就会报出与实际**相反**
 * 的模式 —— 这个字段恰好是拿来回答「屏幕上那些议题是真的吗」的。
 */
export type RunMode = "live" | "demo";

export const runMode = (): RunMode => (process.env.TKOS_MODE === "demo" ? "demo" : "live");

export const isDemo = (): boolean => runMode() === "demo";
