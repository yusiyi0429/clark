#!/usr/bin/env bash
set -euo pipefail

release_id="${1:?release id required}"
archive="${2:?source archive required}"
expected_sha256="${3:?sha256 required}"

app_root="/srv/tokenhub/apps/clark-main"
release_dir="$app_root/releases/$release_id"
data_dir="/srv/tokenhub/data/clark-main"
env_file="/etc/tokenhub/clark-main.env"
nginx_template="/etc/tokenhub/nginx-clark-internal.conf"
nginx_config="/etc/nginx/sites-available/clark-internal.conf"
state_file="$app_root/current.env"
image="clark-main:$release_id"
container="clark-main-$release_id"

test -s "$archive"
test -s "$env_file"
test -s "$nginx_template"

actual_sha256="$(sha256sum "$archive" | awk '{print $1}')"
test "$actual_sha256" = "$expected_sha256"

old_container=""
old_port=""
if test -s "$state_file"; then
  # File is generated by this script and contains only quoted identifiers.
  # shellcheck disable=SC1090
  source "$state_file"
  old_container="${CURRENT_CONTAINER:-}"
  old_port="${CURRENT_PORT:-}"
fi

if test "$old_port" = "3121"; then
  new_port="3122"
else
  new_port="3121"
fi

install -d -m 755 "$app_root/releases" "$data_dir"
chown -R 1001:1001 "$data_dir"
rm -rf "$release_dir"
install -d -m 755 "$release_dir"
tar -xzf "$archive" -C "$release_dir"

if ! docker image inspect node:24-slim >/dev/null 2>&1; then
  docker pull m.daocloud.io/docker.io/library/node:24-slim
  docker tag m.daocloud.io/docker.io/library/node:24-slim node:24-slim
fi

build_started="$(date +%s)"
docker build \
  --build-arg NPM_REGISTRY=https://registry.npmmirror.com \
  --label tokenhub.release="$release_id" \
  -t "$image" "$release_dir"
build_finished="$(date +%s)"

docker rm -f "$container" >/dev/null 2>&1 || true
docker run -d \
  --name "$container" \
  --restart unless-stopped \
  --init \
  --cpus 4 \
  --memory 4g \
  --pids-limit 512 \
  --cap-drop ALL \
  --security-opt no-new-privileges:true \
  --stop-timeout 30 \
  --env-file "$env_file" \
  -e TKOS_CODE_SHA="$release_id" \
  -p "127.0.0.1:$new_port:3000" \
  -v "$data_dir:/app/.data" \
  "$image" >/dev/null

healthy=0
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:$new_port/api/health" >/dev/null; then
    healthy=1
    break
  fi
  sleep 2
done

if test "$healthy" != "1"; then
  docker logs --tail 200 "$container" >&2 || true
  docker rm -f "$container" >/dev/null 2>&1 || true
  exit 1
fi

sed "s/__UPSTREAM_PORT__/$new_port/g" "$nginx_template" > "$nginx_config.new"
if test -f "$nginx_config"; then
  cp "$nginx_config" "$nginx_config.previous"
fi
mv "$nginx_config.new" "$nginx_config"
ln -sfn "$nginx_config" /etc/nginx/sites-enabled/clark-internal.conf
if ! nginx -t; then
  if test -f "$nginx_config.previous"; then
    mv "$nginx_config.previous" "$nginx_config"
  else
    rm -f "$nginx_config" /etc/nginx/sites-enabled/clark-internal.conf
  fi
  docker rm -f "$container" >/dev/null 2>&1 || true
  exit 1
fi
rm -f "$nginx_config.previous"
systemctl reload nginx

cat > "$state_file" <<EOF
CURRENT_RELEASE='$release_id'
CURRENT_CONTAINER='$container'
CURRENT_PORT='$new_port'
EOF
ln -sfn "$release_dir" "$app_root/current"

if test -n "$old_container" && test "$old_container" != "$container"; then
  docker rm -f "$old_container" >/dev/null 2>&1 || true
fi

rm -f "$archive"

printf 'release=%s\n' "$release_id"
printf 'port=%s\n' "$new_port"
printf 'build_seconds=%s\n' "$((build_finished - build_started))"
printf 'health=ok\n'
